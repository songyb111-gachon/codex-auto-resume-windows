def design_rules() -> str:
    """Brand's rules for the four designs, by the design's name: comparisons, never a string switch. Anything that is
    not a design is answered as the default one is, which is what DesignOf reads it as."""
    default = brand.DEFAULT_DESIGN
    if default not in brand.DESIGNS:
        raise ValueError("the default design is one of the designs")
    lines = [
        "        /// A stored Design (v0.6.10) as the settings layer reads it: \"%s\" exactly, and \"%s\" for\n"
        % ('", "'.join(brand.DESIGNS), default),
        "        /// anything else - a missing value, another case, another type.\n",
        "        internal static string DesignOf(object value)\n",
        "        {\n",
        "            string text = value as string;\n",
        "            if (%s) return text;\n" % " || ".join('text == "%s"' % name for name in brand.DESIGNS),
        "            return DesignDefault;\n",
        "        }\n",
        "\n",
        "        /// The design whose colours a design draws in: its own, or %s's (brand.DESIGN_TOKENS).\n" % default,
        "        internal static string DesignColours(string design)\n",
        "        {\n",
    ]
    own = [name for name in brand.DESIGNS if _own_colours(name)]
    for name in own:
        lines.append('            if (design == "%s") return "%s";\n' % (name, name))
    lines += ["            return DesignDefault;\n", "        }\n"]
    for rule, axis, meaning in DESIGN_RULES:
        answer = brand.DESIGN[default][axis]
        other = [name for name in brand.DESIGNS if brand.DESIGN[name][axis] != answer]
        lines += ["\n",
                  "        /// Whether a design %s (brand.DESIGN's %s).\n" % (meaning, axis),
                  "        internal static bool %s(string design)\n" % rule,
                  "        {\n"]
        if other:
            lines.append("            if (%s) return %s;\n"
                         % (" || ".join('design == "%s"' % name for name in other), "true" if not answer else "false"))
        lines += ["            return %s;\n" % ("true" if answer else "false"), "        }\n"]
    roles = tuple(brand.RADII)
    radii = brand.DESIGN_RADII
    for name in brand.DESIGNS:
        if tuple(radii[name]) != roles:
            raise ValueError("every design names the radii by RADII's roles")
        if any(radii[name][role] > radii[default][role] for role in roles):
            raise ValueError("a design's radius is never larger than %s's: nothing measured for it may overflow" % default)
    lines += ["\n",
              "        /// A design's corner radius for one of brand.RADII's roles (\"%s\"), in CSS px\n" % '", "'.join(roles),
              "        /// (brand.DESIGN_RADII) - never larger than %s's. 0 for a role there is none of.\n" % default,
              "        internal static int DesignRadius(string design, string role)\n",
              "        {\n"]
    for name in brand.DESIGNS:
        if name == default or radii[name] == radii[default]:
            continue
        lines += ['            if (design == "%s")\n' % name, "            {\n"]
        for role in roles:
            lines.append('                if (role == "%s") return %s;\n' % (role, _literal("int", radii[name][role])))
        lines += ["                return 0;\n", "            }\n"]
    for role in roles:
        lines.append('            if (role == "%s") return %s;\n' % (role, _literal("int", radii[default][role])))
    lines += ["            return 0;\n", "        }\n",
              "\n",
              "        /// One design in one theme (Brand.Look): `design` as DesignOf reads it, dark or light. What the window\n",
              "        /// adopts, and the one question it asks about a design, so none of its own code names one.\n",
              "        internal static Look LookOf(string design, bool dark)\n",
              "        {\n",
              "            return new Look(design, dark);\n",
              "        }\n"]
    return "".join(lines)


