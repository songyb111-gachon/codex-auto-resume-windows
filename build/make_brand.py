"""Generate `gui/Brand.cs` from the palette in `codex_auto_resume.brand`.

The settings window is C# and cannot import Python, which is exactly how it ended up
with its own copy of the palette and its own drift. So its colours are generated, the
generated file is committed - a contributor with no Python to hand can still read what
the window is going to look like - and `tests/test_brand.py` regenerates it and compares.
A hand-edit to the generated file fails the suite instead of shipping.

Everything is written as a single constant or a method, never as an array. The in-box
compiler stores a constant array initializer in a class it names with a fresh random GUID,
and `build/normalize_pe.py` refuses an executable that carries one: the release would not
be reproducible. For the same reason a rule is a chain of comparisons, never a string switch.

v0.6.4: `Brand` is the light theme and `Brand.Dark` its twin, with the same names for everything
that changes with the theme.

Run: python build/make_brand.py
"""
from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from codex_auto_resume import brand      # noqa: E402

TARGET = ROOT / "gui" / "Brand.cs"

HEADER = """// Generated by build/make_brand.py from src/codex_auto_resume/brand.py.
// Do not edit: tests/test_brand.py regenerates this file and compares it.
//
// Brand is the light theme and Brand.Dark is its dark twin. Every colour, the card's ground, the
// status light's fill, the check box's colours, the elevation recipes and how far they reach
// have the same name in both, so a surface decides its theme once and then reads one set of
// names. Sizes, the glow, the check mark's shape and the High Contrast rules do not change with
// the theme, and live in Brand alone.
//
// The window was light-only until v0.6.4, and that was a measurement: a v0.5.6 probe painted
// the native NumericUpDown, ComboBox and CheckBox in the dark palette, and the parts Windows
// draws - the spinner's buttons, the drop-down's arrow, the check glyph - stayed light. v0.6.4's
// window draws those faces itself, which is what lets it take the dark half. A part Windows
// still draws is the window's to theme, not this file's.

using System;
using System.Drawing;

namespace CodexAutoResume
{
    internal static class Brand
    {
"""

FOOTER = """    }
}
"""

# Only what the window actually draws with. A generated constant nobody uses is a
# compiler warning waiting to happen.
FIELDS = (
    ("Ink", "ink", "text"),
    ("Muted", "muted", "secondary text"),
    ("Line", "line", "hairlines and card edges"),
    ("Surface", "surface", "cards"),
    ("Canvas", "canvas", "the window behind them"),
    ("Accent", "accent", "anything to read or to click"),
    ("OnAccent", "on_accent", "text drawn on the accent"),
    ("Active", "active", "fill only: running"),
    ("Idle", "idle", "fill only: stopped"),
    ("Raised", "raised", "a control resting on a card"),
    ("Inset", "inset", "pressed, selected, a well"),
    ("ShadowDark", "shadow_dark", "shadow below and right of a raised surface"),
    ("ShadowLight", "shadow_light", "highlight above and left of it"),
    ("AccentSoft", "accent_soft", "a quiet accent ground"),
    ("Focus", "focus", "keyboard focus ring"),
    ("Attention", "attention", "fill only: needs a person"),
    ("Success", "success", "recovered"),
    ("Waiting", "waiting", "waiting for a reset or retry"),
    ("Warning", "warning", "needs a decision soon"),
    ("Danger", "danger", "stopped or failed"),
    ("Paused", "paused", "deliberately quiet"),
    ("AccentHover", "accent_hover", "the primary button under the pointer"),
    ("AccentPressed", "accent_pressed", "the primary button pressed"),
)

# Colours a theme derives from its tokens: (name, function of the theme name, note).
DERIVED = (
    ("CardGround", brand.card_ground, "a card's own ground: surface lifted toward raised"),
)

# Which shadow of a light recipe is which, by the token it is drawn in.
_SHADOW_ROLES = {"shadow_dark": "Shadow", "shadow_light": "Highlight"}
_SIDES = ("Top", "Right", "Bottom", "Left")

# The check box's states as C# conditions on (bool on, bool enabled).
_CHECK_CONDITIONS = {"on": "on && enabled", "on_disabled": "on && !enabled",
                     "off": "!on && enabled", "off_disabled": "!on && !enabled"}


def _camel(key: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in key.split("_"))


def _literal(kind: str, value) -> str:
    if kind == "int":
        if int(value) != value:
            raise ValueError("%r is not an integer" % (value,))
        return "%d" % value
    text = "%d" % value if float(value).is_integer() else repr(round(float(value), 6))
    return text + "f" if kind == "float" else text


def sections():
    """Every constant Brand.cs declares after its colours, as (comment, [(name, type, value)]).

    The tests read the compiled file back through reflection and compare each one with this,
    so a name the generator writes is a name the window can be trusted to find.
    """
    scale = []
    for prefix, table in (("Radius", brand.RADII), ("Space", brand.SPACING), ("Type", brand.TYPE)):
        for name, value in table.items():
            scale.append((prefix + _camel(name), "int", int(value)))
    scale.append(("TransitionMs", "int", int(brand.MOTION["transition_ms"])))
    for part, value in zip(("X1", "Y1", "X2", "Y2"), brand.MOTION["ease"]):
        scale.append(("TransitionEase" + part, "double", value))

    layout = []
    for key, value in brand.LAYOUT.items():
        if isinstance(value, tuple):
            for side, part in zip(_SIDES, brand.padding(key)):
                layout.append((_camel(key) + side, "int", part))
        else:
            layout.append((_camel(key), "int", value))

    elevation = []
    for recipe, shadows in brand.SHADOWS["light"].items():
        if any(shadow.inset != (recipe == "inset") for shadow in shadows):
            raise ValueError("the light constants read a recipe's inset-ness from its name: %s" % recipe)
        for shadow in shadows:
            base = "Elev" + _camel(recipe) + _SHADOW_ROLES[shadow.token]
            for part, value in (("Dx", shadow.dx), ("Dy", shadow.dy), ("Blur", shadow.blur),
                                ("Alpha", shadow.alpha)):
                elevation.append((base + part, "float", value))
        for side, value in zip(("Left", "Top", "Right", "Bottom"), brand.reach(recipe)):
            elevation.append(("Elev" + _camel(recipe) + "Reach" + side, "int", value))

    light = [("StatusDotRadius", "double", brand.STATUS_DOT["window"]),
             ("GlowExtent", "double", brand.glow_extent(brand.STATUS_DOT["window"]))]
    for key, value in brand.GLOW.items():
        light.append(("Glow" + _camel(key), "double", value))

    mark = []
    for point, (x, y) in zip(("Start", "Corner", "End"), brand.CHECK_MARK):
        mark.append(("CheckMark" + point + "X", "float", x))
        mark.append(("CheckMark" + point + "Y", "float", y))

    return (
        (None, scale),
        ("The panel's sizes, in CSS px (brand.LAYOUT). A padding is written Top, Right, Bottom, Left.",
         layout),
        ("The panel's light elevation (brand.SHADOWS): one shadow in ShadowDark and one highlight in\n"
         "        // ShadowLight per recipe, in CSS px, and how far each recipe reaches past its box. A blur\n"
         "        // B is a Gaussian with sigma B/2. The inset recipe is drawn inside the box. Dark's recipes\n"
         "        // are another shape: read both themes through ElevationCount and ElevationShadow.",
         elevation),
        ("The status light (brand.STATUS_DOT, brand.GLOW): the dot keeps its size, and the glow's\n"
         "        // numbers are the popup's and the panel's too.",
         light),
        ("The check box's mark (brand.CHECK_MARK): the centre line's start, corner and end in CSS px\n"
         "        // from the box's outer top-left corner, on a CheckSize box. Stroke it CheckStroke wide with\n"
         "        // flat ends and a mitred corner; brand.check_mark_outline is the same shape filled.",
         mark),
    )


def dark_sections():
    """The constants Brand.Dark declares, in the same shape as sections()."""
    reach = []
    for recipe in brand.SHADOWS["dark"]:
        for side, value in zip(("Left", "Top", "Right", "Bottom"), brand.reach(recipe, "dark")):
            reach.append(("Elev" + _camel(recipe) + "Reach" + side, "int", value))
    return (
        ("How far each dark elevation recipe reaches past its box, in CSS px (brand.reach).", reach),
    )


def _condition(states) -> str:
    return " || ".join('state == "%s"' % state for state in states)


def _grouped(table, fallback):
    groups = {}
    for state, value in table.items():
        if value != fallback:
            groups.setdefault(value, []).append(state)
    return groups.items()


def _check_condition(states) -> str:
    if len(states) == 1:
        return _CHECK_CONDITIONS[states[0]]
    return " || ".join("(%s)" % _CHECK_CONDITIONS[state] for state in states)


def _check_rule(table, part, name_of) -> list:
    """`if (...) return X;` lines for one part of a check box table, grouped by what they return,
    ending in what a disabled, unchecked box returns."""
    fallback = name_of(table["off_disabled"][part])
    groups = {}
    for state, entry in table.items():
        name = name_of(entry[part])
        if name != fallback:
            groups.setdefault(name, []).append(state)
    lines = ["            if (%s) return %s;\n" % (_check_condition(states), name)
             for name, states in groups.items()]
    lines.append("            return %s;\n" % fallback)
    return lines


def _check_mark_rule(table, name_of) -> list:
    lines = ["            mark = Color.Empty;\n"]
    for state, entry in table.items():
        if entry["mark"] is not None:
            lines.append("            if (%s) { mark = %s; return true; }\n"
                         % (_CHECK_CONDITIONS[state], name_of(entry["mark"])))
    lines.append("            return false;\n")
    return lines


def status_fill_method() -> str:
    """StatusFill, which Brand and Brand.Dark each declare: its names resolve to their own colours."""
    field = {token: name for name, token, _ in FIELDS}
    if brand.status_fill("an unknown state") != "idle":
        raise ValueError("the generated rules fall back to idle grey")
    lines = [
        "        /// The colour a state's dot and its glow are filled with; anything unknown is idle grey.\n",
        "        internal static Color StatusFill(string state)\n",
        "        {\n",
    ]
    for token, states in _grouped(brand.STATUS_FILL, "idle"):
        lines.append("            if (%s) return %s;\n" % (_condition(states), field[token]))
    lines += ["            return Idle;\n", "        }\n"]
    return "".join(lines)


def methods() -> str:
    """The status light's rules, written out from brand.py's tables.

    Comparisons rather than a switch: a string switch with enough cases makes the in-box
    compiler emit the randomly named class that stops a reproducible build.
    """
    if brand.status_system("an unknown state") != "GrayText":
        raise ValueError("the generated rules fall back to idle grey")
    lines = [status_fill_method(), "\n",
             "        /// The same dot in High Contrast: a system colour, and never a glow.\n",
             "        internal static Color StatusSystem(string state)\n",
             "        {\n"]
    for name, states in _grouped(brand.STATUS_SYSTEM, "GrayText"):
        lines.append("            if (%s) return SystemColors.%s;\n" % (_condition(states), name))
    lines += ["            return SystemColors.GrayText;\n", "        }\n", "\n"]
    lines += [
        "        /// The glow around the status dot for one frame, or false when the state has none.\n",
        "        /// brand.glow() in C#: `arc` is the checking arc's start angle in degrees, or -1, and a\n",
        "        /// negative or NaN sinceEnteredMs means the state's one pulse is over. The caller draws\n",
        "        /// no glow in High Contrast.\n",
        "        internal static bool Glow(string state, double elapsedMs, double sinceEnteredMs, bool reduced,\n",
        "                                  out double opacity, out double scale, out double arc)\n",
        "        {\n",
        "            opacity = 0;\n",
        "            scale = 1;\n",
        "            arc = -1;\n",
    ]
    for state in brand.GLOW_BREATHES:
        name = _camel(state)
        lines += [
            "            if (%s)\n" % _condition((state,)),
            "                return Breathe(elapsedMs, reduced, Glow%sMs, Glow%sLow, Glow%sHigh,\n" % (name, name, name),
            "                               Glow%sScaleLow, Glow%sScaleHigh, out opacity, out scale);\n" % (name, name),
        ]
    lines += [
        '            if (state == "waiting")\n',
        "            {\n",
        "                opacity = GlowStill;\n",
        "                return true;\n",
        "            }\n",
        '            if (state == "checking")\n',
        "            {\n",
        "                opacity = GlowStill;\n",
        "                arc = reduced ? GlowArcStillAt : elapsedMs % GlowArcMs / GlowArcMs * 360.0;\n",
        "                return true;\n",
        "            }\n",
        "            if (%s)\n" % _condition(brand.GLOW_PULSES),
        "            {\n",
        "                opacity = GlowStill;\n",
        "                if (!reduced && sinceEnteredMs >= 0 && sinceEnteredMs < GlowAttentionMs)\n",
        "                    opacity = GlowStill + (GlowAttentionPeak - GlowStill) * Breath(sinceEnteredMs, GlowAttentionMs);\n",
        "                return true;\n",
        "            }\n",
        "            return false;\n",
        "        }\n",
        "\n",
        "        /// Whether a frame timer has anything to draw for this state.\n",
        "        internal static bool GlowMoves(string state, double sinceEnteredMs, bool reduced)\n",
        "        {\n",
        "            if (reduced) return false;\n",
        '            if (%s || state == "checking") return true;\n' % _condition(brand.GLOW_BREATHES),
        "            return (%s) && sinceEnteredMs >= 0 && sinceEnteredMs < GlowAttentionMs;\n"
        % _condition(brand.GLOW_PULSES),
        "        }\n",
        "\n",
        "        private static bool Breathe(double elapsedMs, bool reduced, double cycleMs, double low, double high,\n",
        "                                    double small, double large, out double opacity, out double scale)\n",
        "        {\n",
        "            if (reduced)\n",
        "            {\n",
        "                opacity = (low + high) / 2;\n",
        "                scale = 1;\n",
        "                return true;\n",
        "            }\n",
        "            double wave = Breath(elapsedMs, cycleMs);\n",
        "            opacity = low + (high - low) * wave;\n",
        "            scale = small + (large - small) * wave;\n",
        "            return true;\n",
        "        }\n",
        "\n",
        "        /// 0 at the start of a cycle, 1 halfway, 0 again: a raised cosine.\n",
        "        private static double Breath(double elapsedMs, double cycleMs)\n",
        "        {\n",
        "            return 0.5 - 0.5 * Math.Cos(2 * Math.PI * (elapsedMs % cycleMs) / cycleMs);\n",
        "        }\n",
    ]
    lines += ["\n"] + ease_method()
    return "".join(lines)


def ease_method() -> list:
    """brand.ease() in C#: how far a transition has come after `progress` of its time, on the
    TransitionEase curve - the same Newton steps, then halving, so a switch glides along one path
    in the window, the popup and the panel."""
    return [
        "        /// How far a transition has come, 0 to 1, after `progress` of TransitionMs: brand.ease(), the\n",
        "        /// CSS cubic-bezier TransitionEaseX1, Y1, X2, Y2. Held at 0 before the start and 1 after the end.\n",
        "        internal static double Ease(double progress)\n",
        "        {\n",
        "            if (!(progress > 0)) return 0;\n",
        "            if (progress >= 1) return 1;\n",
        "            double t = progress;\n",
        "            for (int i = 0; i < 8; i++)\n",
        "            {\n",
        "                double error = Bezier(TransitionEaseX1, TransitionEaseX2, t) - progress;\n",
        "                if (Math.Abs(error) < 1e-7) return Bezier(TransitionEaseY1, TransitionEaseY2, t);\n",
        "                double slope = BezierSlope(TransitionEaseX1, TransitionEaseX2, t);\n",
        "                if (Math.Abs(slope) < 1e-6) break;\n",
        "                t = Math.Min(1.0, Math.Max(0.0, t - error / slope));\n",
        "            }\n",
        "            double low = 0, high = 1;\n",
        "            t = progress;\n",
        "            for (int i = 0; i < 40; i++)\n",
        "            {\n",
        "                double value = Bezier(TransitionEaseX1, TransitionEaseX2, t);\n",
        "                if (Math.Abs(value - progress) < 1e-7) break;\n",
        "                if (value < progress) low = t; else high = t;\n",
        "                t = (low + high) / 2.0;\n",
        "            }\n",
        "            return Bezier(TransitionEaseY1, TransitionEaseY2, t);\n",
        "        }\n",
        "\n",
        "        private static double Bezier(double a, double b, double t)\n",
        "        {\n",
        "            return ((1.0 - 3.0 * b + 3.0 * a) * t + (3.0 * b - 6.0 * a)) * t * t + 3.0 * a * t;\n",
        "        }\n",
        "\n",
        "        private static double BezierSlope(double a, double b, double t)\n",
        "        {\n",
        "            return 3.0 * (1.0 - 3.0 * b + 3.0 * a) * t * t + 2.0 * (3.0 * b - 6.0 * a) * t + 3.0 * a;\n",
        "        }\n",
    ]


def theme_methods(theme: str) -> str:
    """The rules whose answers are a theme's colours - the check box and the elevation recipes -
    which Brand and Brand.Dark each declare under the same names."""
    field = {token: name for name, token, _ in FIELDS}
    for entry in brand.CHECKBOX.values():
        for part in ("fill", "edge", "mark"):
            if entry[part] is not None and entry[part] not in field:
                raise ValueError("Brand.cs declares no colour for the check box's %s" % entry[part])
    lines = [
        "        /// The check box's fill (brand.CHECKBOX): the well unchecked, the accent checked, the surface\n",
        "        /// when disabled. `on` is checked; draw the inset elevation inside the border when CheckWell.\n",
        "        internal static Color CheckFill(bool on, bool enabled)\n",
        "        {\n",
    ]
    lines += _check_rule(brand.CHECKBOX, "fill", field.__getitem__)
    lines += [
        "        }\n",
        "\n",
        "        /// The check box's hairline edge: muted unchecked, where nothing inside says it is a box.\n",
        "        internal static Color CheckEdge(bool on, bool enabled)\n",
        "        {\n",
    ]
    lines += _check_rule(brand.CHECKBOX, "edge", field.__getitem__)
    lines += [
        "        }\n",
        "\n",
        "        /// The check mark's colour, or false when the box has no mark.\n",
        "        internal static bool CheckMark(bool on, bool enabled, out Color mark)\n",
        "        {\n",
    ]
    lines += _check_mark_rule(brand.CHECKBOX, field.__getitem__)
    lines += [
        "        }\n",
        "\n",
        "        /// How many shadows an elevation recipe (\"card\", \"control\" or \"inset\") has; 0 for any other.\n",
        "        internal static int ElevationCount(string recipe)\n",
        "        {\n",
    ]
    recipes = brand.SHADOWS[theme]
    for recipe, listed in recipes.items():
        lines.append('            if (recipe == "%s") return %d;\n' % (recipe, len(listed)))
    lines += [
        "            return 0;\n",
        "        }\n",
        "\n",
        "        /// Shadow `index` of an elevation recipe (brand.SHADOWS), front to back as the panel's\n",
        "        /// stylesheet lists them, so paint from the last to the first. In CSS px: the offset, the\n",
        "        /// blur (a Gaussian with sigma blur / 2), the alpha, whether it falls inside the box rather\n",
        "        /// than around it, and its colour. False past the last shadow.\n",
        "        internal static bool ElevationShadow(string recipe, int index, out double dx, out double dy,\n",
        "                                             out double blur, out double alpha, out bool inset, out Color tone)\n",
        "        {\n",
        "            dx = 0;\n",
        "            dy = 0;\n",
        "            blur = 0;\n",
        "            alpha = 0;\n",
        "            inset = false;\n",
        "            tone = Color.Empty;\n",
    ]
    for recipe, listed in recipes.items():
        lines += ['            if (recipe == "%s")\n' % recipe, "            {\n"]
        for index, shadow in enumerate(listed):
            lines.append("                if (index == %d) { dx = %s; dy = %s; blur = %s; alpha = %s;%s tone = %s; return true; }\n"
                         % (index, _literal("double", shadow.dx), _literal("double", shadow.dy),
                            _literal("double", shadow.blur), _literal("double", shadow.alpha),
                            " inset = true;" if shadow.inset else "", field[shadow.token]))
        lines += ["                return false;\n", "            }\n"]
    lines += ["            return false;\n", "        }\n"]
    return "".join(lines)


def check_rules() -> str:
    """The check box's rules that do not change with the theme: the well, and High Contrast."""
    wells = [state for state, entry in brand.CHECKBOX.items() if entry["well"]]

    def system(name):
        return "SystemColors." + name

    lines = [
        "        /// Whether the check box draws the inset elevation inside its border, in either theme.\n",
        "        /// Never in High Contrast.\n",
        "        internal static bool CheckWell(bool on, bool enabled)\n",
        "        {\n",
        "            return %s;\n" % (_check_condition(wells) if wells else "false"),
        "        }\n",
        "\n",
        "        /// The check box in High Contrast (brand.CHECKBOX_SYSTEM): system colours, and no shadow.\n",
        "        internal static Color CheckSystemFill(bool on, bool enabled)\n",
        "        {\n",
    ]
    lines += _check_rule(brand.CHECKBOX_SYSTEM, "fill", system)
    lines += ["        }\n", "\n",
              "        internal static Color CheckSystemEdge(bool on, bool enabled)\n",
              "        {\n"]
    lines += _check_rule(brand.CHECKBOX_SYSTEM, "edge", system)
    lines += ["        }\n", "\n",
              "        internal static bool CheckSystemMark(bool on, bool enabled, out Color mark)\n",
              "        {\n"]
    lines += _check_mark_rule(brand.CHECKBOX_SYSTEM, system)
    lines.append("        }\n")
    return "".join(lines)


def _colours(theme: str, indent: str) -> list:
    tokens = brand.palette(theme)
    rows = [(name, tokens[token], note) for name, token, note in FIELDS]
    rows += [(name, function(theme), note) for name, function, note in DERIVED]
    width = max(len(name) for name, _, _ in rows)
    lines = []
    for name, value, note in rows:
        red, green, blue = brand.rgb(value)
        lines.append(
            "%sinternal static readonly Color %s = Color.FromArgb(0x%02X, 0x%02X, 0x%02X);"
            "  // %s, %s\n" % (indent, name.ljust(width), red, green, blue, value, note))
    return lines


def _nested(text: str) -> str:
    """A member written for Brand, indented one level further for Brand.Dark."""
    return "".join("    " + line if line.strip() else line for line in text.splitlines(True))


def dark_class() -> str:
    lines = [
        "\n",
        "        /// The dark theme (brand.DARK and the dark elevation), under the same names Brand gives the\n",
        "        /// light one. The Codex panel in dark is what it is held to.\n",
        "        internal static class Dark\n",
        "        {\n",
    ]
    lines += _colours("dark", "            ")
    declared = set(name for name, _, _ in FIELDS + DERIVED)
    for comment, constants in dark_sections():
        lines.append("\n")
        lines.append("            // %s\n" % comment)
        for name, kind, value in constants:
            if name in declared:
                raise ValueError("Brand.Dark would declare %s twice" % name)
            declared.add(name)
            lines.append("            internal const %s %s = %s;\n" % (kind, name, _literal(kind, value)))
    lines += ["\n", _nested(status_fill_method()), "\n", _nested(theme_methods("dark")), "        }\n"]
    return "".join(lines)


def render() -> str:
    lines = [HEADER]
    lines += _colours("light", "        ")
    declared = set(name for name, _, _ in FIELDS + DERIVED)
    for index, (comment, constants) in enumerate(sections()):
        lines.append("\n")
        if comment:
            lines.append("        // %s\n" % comment)
        for name, kind, value in constants:
            if name in declared:
                raise ValueError("Brand.cs would declare %s twice" % name)
            declared.add(name)
            lines.append("        internal const %s %s = %s;\n" % (kind, name, _literal(kind, value)))
        if index == 0:
            lines.append("\n")
            lines.append('        internal const string HexAccent = "%s";\n' % brand.LIGHT["accent"])
            lines.append('        internal const string HexBrand = "%s";\n' % brand.BRAND)
    lines += ["\n", methods(), "\n", theme_methods("light"), "\n", check_rules(), dark_class(), FOOTER]
    return "".join(lines)


def main(argv=None) -> int:
    text = render()
    check = bool(argv) and argv[0] == "--check"
    if check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print("gui/Brand.cs is out of date; run python build/make_brand.py")
            return 1
        print("gui/Brand.cs matches the palette")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print("wrote %s" % TARGET)
    return 0


