def _colour_class(design: str, theme: str) -> str:
    """The class that declares a design's colours in a theme: Brand, Brand.Dark, Brand.Classic, Brand.Classic.Dark..."""
    owner = "Brand" if not _own_colours(design) else "Brand." + _camel(design)
    return owner + (".Dark" if theme == "dark" else "")


def _assignments(names, source: str, indent: str, width: int = 120) -> list:
    """`Name = source.Name;` for each name, on as few lines as fit in `width` columns."""
    lines, line = [], indent
    for name in names:
        item = "%s = %s.%s;" % (name, source, name)
        if line != indent and len(line) + 1 + len(item) > width:
            lines.append(line + "\n")
            line = indent
        line += item if line == indent else " " + item
    if line != indent:
        lines.append(line + "\n")
    return lines


