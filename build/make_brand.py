"""Generate `gui/Brand.cs` from the palette in `codex_auto_resume.brand`.

The settings window is C# and cannot import Python, which is exactly how it ended up
with its own copy of the palette and its own drift. So its colours are generated, the
generated file is committed - a contributor with no Python to hand can still read what
the window is going to look like - and `tests/test_brand.py` regenerates it and compares.
A hand-edit to the generated file fails the suite instead of shipping.

Run: python build/make_brand.py
"""
from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from codex_auto_resume import brand      # noqa: E402

TARGET = ROOT / "gui" / "Brand.cs"

HEADER = """// Generated by build/make_brand.py from src/codex_auto_resume/brand.py.
// Do not edit: tests/test_brand.py regenerates this file and compares it.
//
// The window is light-only, and that is a measurement rather than an opinion.
//
// A probe built for v0.5.6 painted a card, a NumericUpDown, a ComboBox, a CheckBox and a
// Button in the dark palette and photographed the result. The body went dark; the parts
// Windows draws did not. The spinner's up/down block, the drop-down's arrow block and the
// checkbox glyph all stayed light, so the window came out dark with three white rectangles
// in it - worse than an honestly light window, and not fixable without owner-drawing every
// native control.
//
// The dark half of the palette is not unused: the Codex panel is HTML, follows the host's
// colour scheme, and was rebalanced in the same release.

using System.Drawing;

namespace CodexAutoResume
{
    internal static class Brand
    {
"""

FOOTER = """    }
}
"""

# Only what the window actually draws with. A generated constant nobody uses is a
# compiler warning waiting to happen.
FIELDS = (
    ("Ink", "ink", "text"),
    ("Muted", "muted", "secondary text"),
    ("Line", "line", "hairlines and card edges"),
    ("Surface", "surface", "cards"),
    ("Canvas", "canvas", "the window behind them"),
    ("Accent", "accent", "anything to read or to click"),
    ("OnAccent", "on_accent", "text drawn on the accent"),
    ("Active", "active", "fill only: running"),
    ("Idle", "idle", "fill only: stopped"),
)


def render() -> str:
    lines = [HEADER]
    width = max(len(name) for name, _, _ in FIELDS)
    for name, token, note in FIELDS:
        value = brand.LIGHT[token]
        red, green, blue = brand.rgb(value)
        lines.append(
            "        internal static readonly Color %s = Color.FromArgb(0x%02X, 0x%02X, 0x%02X);"
            "  // %s, %s\n" % (name.ljust(width), red, green, blue, value, note))
    lines.append("\n")
    lines.append('        internal const string HexAccent = "%s";\n' % brand.LIGHT["accent"])
    lines.append('        internal const string HexBrand = "%s";\n' % brand.BRAND)
    lines.append(FOOTER)
    return "".join(lines)


def main(argv=None) -> int:
    text = render()
    check = bool(argv) and argv[0] == "--check"
    if check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print("gui/Brand.cs is out of date; run python build/make_brand.py")
            return 1
        print("gui/Brand.cs matches the palette")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print("wrote %s" % TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
