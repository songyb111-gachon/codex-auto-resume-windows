"""Generate `gui/Brand.cs` from the palette in `codex_auto_resume.brand`.

The settings window is C# and cannot import Python, which is exactly how it ended up
with its own copy of the palette and its own drift. So its colours are generated, the
generated file is committed - a contributor with no Python to hand can still read what
the window is going to look like - and `tests/test_brand.py` regenerates it and compares.
A hand-edit to the generated file fails the suite instead of shipping.

Everything is written as a single constant or a method, never as an array. The in-box
compiler stores a constant array initializer in a class it names with a fresh random GUID,
and `build/normalize_pe.py` refuses an executable that carries one: the release would not
be reproducible. For the same reason a rule is a chain of comparisons, never a string switch.

v0.6.4: `Brand` is the light theme and `Brand.Dark` its twin, with the same names for everything
that changes with the theme.

v0.6.5: `Brand.Mark` is the notification-area icon's motion for the window's taskbar button - the
icon's rule, its numbers and its frames, from `codex_auto_resume.ui.tray`. The frames are the icon's
own pixels (tray.IconFrames), written as strings: one drawing, and nothing for the window to render.

v0.6.10: the four designs (brand/design.py). Every design with colours of its own - Classic and Plain;
Still draws in Soft's - is a class beside `Brand.Dark`, `Brand.Classic` and `Brand.Classic.Dark` and so
on, with the colour names, the card's ground and the check box Brand gives Soft's. What else a design
decides - depth, the glow, the breath, the glides, the accent bar, the radii - is a rule in Brand that
takes the design's name (`DesignDepth("plain")`), written as a chain of comparisons, and `DesignOf` reads
a stored value exactly as the settings layer does. `Brand.LookOf(design, dark)` is all of that for one design
in one theme - its colours and check box, its rules' answers and its corners - and the only thing the window's
own code asks: choosing a design's classes by its name is generated here, so no hand-written line names one.

Run: python build/make_brand.py
"""
