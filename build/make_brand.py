def mark_frames(size: int) -> bytes:
    """One size's frames as the window reads them (MarkFrames in gui/Controls.cs): tray.IconFrames' own.

    First the ground - the mark without its head, top-down BGRA with straight alpha - as runs of equal
    pixels: a count from 1 to 255, then blue, green, red and alpha. Then, for each head position in turn,
    the box its head can touch (left, top, right, bottom) and one entry per pixel of it, row by row:
    MARK_GROUND where no sample is the head (the ground stands), MARK_HEAD where every sample is (the
    head's colour, opaque), and otherwise MARK_SAMPLES and the pixel's samples as IconFrames keeps
    them - how many fall on the badge, how many of those are the head, and the others' red, green and
    blue sums, two bytes each, low byte first. The window composes a frame with IconFrames.compose's
    arithmetic; read back here the same way, every position must give IconFrames' own frame, or nothing
    is written.
    """
    frames = tray.IconFrames(size)
    ground = frames.ground
    out = bytearray()
    start = 0
    while start < len(ground):
        pixel = ground[start:start + 4]
        count = 1
        while count < 255 and ground[start + 4 * count:start + 4 * count + 4] == pixel:
            count += 1
        out.append(count)
        out += pixel
        start += 4 * count
    whole = brand.ICON_SUPERSAMPLE * brand.ICON_SUPERSAMPLE
    for (left, top, right, bottom), rows in frames.heads:
        out += bytes((left, top, right, bottom))
        for y, row in enumerate(rows):
            for x, sample in enumerate(row):
                covered, heads, red, green, blue = sample
                if heads == 0:
                    index = ((top + y) * size + left + x) * 4
                    red_, green_, blue_, alpha = brand.icon_pixel(sample, (0, 0, 0))
                    if bytes((blue_, green_, red_, alpha)) != ground[index:index + 4]:
                        raise ValueError("a pixel the head does not touch is not the ground's")
                    out.append(MARK_GROUND)
                elif covered == heads == whole:
                    out.append(MARK_HEAD)
                else:
                    out.append(MARK_SAMPLES)
                    out += bytes((covered, heads)) + struct.pack("<HHH", red, green, blue)
    data = bytes(out)
    for position in range(tray.ICON_MOTION["positions"]):
        for colour in (brand.rgb(brand.ICON_ACCENT), (0, 0, 0), (255, 255, 255), (201, 7, 99)):
            if mark_compose(data, size, position, colour) != frames.compose(position, colour):
                raise ValueError("the frames read back differ from the icon's own at %d px" % size)
    return data


def mark_compose(data: bytes, size: int, position: int, head) -> bytes:
    """One frame from mark_frames' bytes: the head at `position` in `head` (red, green, blue), top-down BGRA.

    What MarkFrames.Compose does in the window, written again here only to prove the bytes."""
    pixels = bytearray()
    at = 0
    while len(pixels) < size * size * 4:
        pixels += data[at + 1:at + 5] * data[at]
        at += 5
    if len(pixels) != size * size * 4:
        raise ValueError("the ground's runs overrun the icon")
    whole = brand.ICON_SUPERSAMPLE * brand.ICON_SUPERSAMPLE
    for index in range(tray.ICON_MOTION["positions"]):
        left, top, right, bottom = data[at:at + 4]
        at += 4
        for y in range(top, bottom):
            for x in range(left, right):
                kind = data[at]
                at += 1
                if kind == MARK_GROUND:
                    continue
                if kind == MARK_HEAD:
                    covered, heads, red, green, blue = whole, whole, 0, 0, 0
                else:
                    covered, heads = data[at], data[at + 1]
                    red, green, blue = struct.unpack_from("<HHH", data, at + 2)
                    at += 8
                if index != position:
                    continue
                offset = (y * size + x) * 4
                pixel = brand.icon_pixel((covered, heads, red, green, blue), tuple(head))
                pixels[offset:offset + 4] = bytes((pixel[2], pixel[1], pixel[0], pixel[3]))
    if at != len(data):
        raise ValueError("the frames have bytes nothing reads")
    return bytes(pixels)


def _mark_colour(rgb) -> str:
    return "Color.FromArgb(0x%02X, 0x%02X, 0x%02X)" % tuple(rgb)


def mark_class() -> str:
    """Brand.Mark: the notification-area icon's motion, as the window's taskbar button shows it."""
    motion = tray.ICON_MOTION
    if set(tray.ICON_FOR_LIGHT) != set(brand.STATUS_FILL):
        raise ValueError("every status light has an icon state, and anything else is idle")
    unknown = tray.icon_head_colour("an unknown state")
    breathers = [state for state in tray.ICON_STATES if tray.icon_brand_state(state) in brand.GLOW_BREATHES]
    pulses = [state for state in tray.ICON_STATES if tray.icon_brand_state(state) in brand.GLOW_PULSES]
    if breathers != ["watching", "recovering"] or pulses != ["attention", "failed"]:
        raise ValueError("Brand.Mark turns watching and recovering, which are the ones that breathe")
    dim = brand.rgb(tray.ICON_DIM_TOWARD)
    lines = [
        "\n",
        "        /// The notification-area icon's motion on the window's taskbar button (v0.6.5), from\n",
        "        /// codex_auto_resume.tray: the icon's five states and the one each status light is drawn as, its\n",
        "        /// rhythms, and its frames at every size the window's big icon has. TaskbarMark shows them.\n",
        "        internal static class Mark\n",
        "        {\n",
        "            // tray.ICON_MOTION. The icon also reads four of brand.GLOW's rhythms, which Brand declares:\n",
        "            // GlowMonitoringMs and GlowRecoveringMs (the breaths), GlowArcMs (recovering's turn) and\n",
        "            // GlowAttentionMs (a problem's one pulse).\n",
        "            internal const double TurnEveryMs = %s;\n" % _literal("double", motion["turn_every_ms"]),
        "            internal const double TurnMs = %s;\n" % _literal("double", motion["turn_ms"]),
        "            internal const int BreatheFrameMs = %s;\n" % _literal("int", motion["breathe_frame_ms"]),
        "            internal const int TurnFrameMs = %s;\n" % _literal("int", motion["turn_frame_ms"]),
        "            internal const int Positions = %s;\n" % _literal("int", motion["positions"]),
        "            internal const int Levels = %s;\n" % _literal("int", motion["levels"]),
        "            internal const double Dim = %s;\n" % _literal("double", motion["dim"]),
        "            // A pixel's samples: brand.ICON_SUPERSAMPLE squared.\n",
        "            internal const int Samples = %d;\n" % (brand.ICON_SUPERSAMPLE * brand.ICON_SUPERSAMPLE),
        "            // What a head pixel's entry in the frames starts with (build/make_brand.py, mark_frames).\n",
        "            internal const int EntryGround = %d;\n" % MARK_GROUND,
        "            internal const int EntryHead = %d;\n" % MARK_HEAD,
        "            internal const int EntrySamples = %d;\n" % MARK_SAMPLES,
        "\n",
        "            /// The icon's state for the state a status light shows (tray.ICON_FOR_LIGHT); anything\n",
        "            /// unknown is idle.\n",
        "            internal static string IconState(string light)\n",
        "            {\n",
    ]
    groups = {}
    for light, state in tray.ICON_FOR_LIGHT.items():
        if state != "idle":
            groups.setdefault(state, []).append(light)
    for state, lights in groups.items():
        lines.append("                if (%s) return \"%s\";\n"
                     % (" || ".join('light == "%s"' % light for light in lights), state))
    lines += [
        '                return "idle";\n',
        "            }\n",
        "\n",
        "            /// The head's full colour in an icon state (tray.icon_head_colour); anything unknown is idle's.\n",
        "            internal static Color HeadColour(string state)\n",
        "            {\n",
    ]
    colours = {}
    for state in tray.ICON_STATES:
        colour = tray.icon_head_colour(state)
        if colour != unknown:
            colours.setdefault(colour, []).append(state)
    for colour, states in colours.items():
        lines.append("                if (%s) return %s;\n" % (_condition(states), _mark_colour(colour)))
    lines += [
        "                return %s;\n" % _mark_colour(unknown),
        "            }\n",
        "\n",
        "            /// The head's colour at breathing `level` (tray.icon_level_colour): the top level is `colour`, the\n",
        "            /// lowest Dim of the way toward the badge's deep blue.\n",
        "            internal static Color LevelColour(Color colour, int level)\n",
        "            {\n",
        "                int top = Levels - 1;\n",
        "                level = Math.Max(0, Math.Min(top, level));\n",
        "                double amount = Dim * (top - level) / (double)top;\n",
        "                return Color.FromArgb(Toward(colour.R, 0x%02X, amount), Toward(colour.G, 0x%02X, amount),\n" % dim[:2],
        "                                      Toward(colour.B, 0x%02X, amount));\n" % dim[2],
        "            }\n",
        "\n",
        "            private static int Toward(int one, int other, double amount)\n",
        "            {\n",
        "                return (int)Math.Floor(one + (other - one) * amount + 0.5);\n",
        "            }\n",
        "\n",
        "            /// How far round the ring the head has travelled, in degrees, or -1 at rest (tray.icon_turn):\n",
        "            /// watching once in the last TurnMs of every TurnEveryMs, eased in and out; recovering all the\n",
        "            /// time, once per GlowArcMs.\n",
        "            internal static double Turn(string state, double elapsedMs)\n",
        "            {\n",
        '                if (state == "recovering") return 360.0 * (elapsedMs % GlowArcMs) / GlowArcMs;\n',
        '                if (state == "watching")\n',
        "                {\n",
        "                    double into = elapsedMs % TurnEveryMs - (TurnEveryMs - TurnMs);\n",
        "                    if (into < 0) return -1;\n",
        "                    return 360.0 * (0.5 - 0.5 * Math.Cos(Math.PI * Math.Min(1.0, into / TurnMs)));\n",
        "                }\n",
        "                return -1;\n",
        "            }\n",
        "\n",
        "            /// One frame, as (position, level) (tray.icon_frame): position 0 is the head in its place, the\n",
        "            /// top level its full colour. With motion reduced every state is at rest. A negative\n",
        "            /// sinceEnteredMs means the state's one pulse is over.\n",
        "            internal static void Frame(string state, double elapsedMs, double sinceEnteredMs, bool reduced,\n",
        "                                       out int position, out int level)\n",
        "            {\n",
        "                position = 0;\n",
        "                level = Levels - 1;\n",
        "                if (reduced) return;\n",
        "                double turn = Turn(state, elapsedMs);\n",
        "                if (turn >= 0) position = (int)Math.Round(turn / (360.0 / Positions)) % Positions;\n",
    ]
    for state in breathers:
        lines += [
            '                if (state == "%s")\n' % state,
            "                {\n",
            "                    level = BreathLevel(elapsedMs, Glow%sMs);\n" % _camel(tray.icon_brand_state(state)),
            "                    return;\n",
            "                }\n",
        ]
    lines += [
        "                position = 0;\n",
        "                if ((%s) && sinceEnteredMs >= 0 && sinceEnteredMs < GlowAttentionMs)\n" % _condition(pulses),
        "                    level = BreathLevel(sinceEnteredMs, GlowAttentionMs);\n",
        "            }\n",
        "\n",
        "            /// How soon the next frame is due, in ms, or -1 when nothing moves (tray.icon_frame_ms).\n",
        "            internal static int FrameMs(string state, double elapsedMs, double sinceEnteredMs, bool reduced)\n",
        "            {\n",
        "                if (reduced) return -1;\n",
        '                if (state == "recovering") return TurnFrameMs;\n',
        '                if (state == "watching") return Turn(state, elapsedMs) >= 0 ? TurnFrameMs : BreatheFrameMs;\n',
        "                if ((%s) && sinceEnteredMs >= 0 && sinceEnteredMs < GlowAttentionMs)\n" % _condition(pulses),
        "                    return BreatheFrameMs;\n",
        "                return -1;\n",
        "            }\n",
        "\n",
        "            /// Full colour at the start of a cycle, dimmest halfway, full again (tray._breath_level).\n",
        "            private static int BreathLevel(double elapsedMs, double cycleMs)\n",
        "            {\n",
        "                return (int)Math.Round((Levels - 1) * (1.0 - Breath(elapsedMs, cycleMs)));\n",
        "            }\n",
        "\n",
        "            /// The frames for a big icon of `size` px, base64 (build/make_brand.py, mark_frames), or null\n",
        "            /// for a size there are none of.\n",
        "            internal static string Frames(int size)\n",
        "            {\n",
    ]
    for size in MARK_SIZES:
        lines.append("                if (size == %d) return Frames%d();\n" % (size, size))
    lines += ["                return null;\n", "            }\n"]
    # Methods, not constants: a string constant is kept twice in the executable - where it is loaded and as
    # the field's value - and these strings are most of its size.
    for size in MARK_SIZES:
        text = base64.b64encode(mark_frames(size)).decode("ascii")
        chunks = [text[at:at + MARK_LINE] for at in range(0, len(text), MARK_LINE)]
        lines += ["\n", "            private static string Frames%d()\n" % size, "            {\n",
                  "                return\n"]
        for index, chunk in enumerate(chunks):
            lines.append('                    "%s"%s\n' % (chunk, ";" if index == len(chunks) - 1 else " +"))
        lines.append("            }\n")
    lines.append("        }\n")
    return "".join(lines)


def render() -> str:
    lines = [HEADER]
    lines += _colours("light", "        ")
    declared = set(name for name, _, _ in FIELDS + DERIVED)
    for index, (comment, constants) in enumerate(sections()):
        lines.append("\n")
        if comment:
            lines.append("        // %s\n" % comment)
        for name, kind, value in constants:
            if name in declared:
                raise ValueError("Brand.cs would declare %s twice" % name)
            declared.add(name)
            lines.append("        internal const %s %s = %s;\n" % (kind, name, _literal(kind, value)))
        if index == 0:
            lines.append("\n")
            lines.append('        internal const string HexAccent = "%s";\n' % brand.LIGHT["accent"])
            lines.append('        internal const string HexBrand = "%s";\n' % brand.BRAND)
    lines += ["\n", methods(), "\n", theme_methods("light"), "\n", check_rules(), dark_class(), mark_class(),
              FOOTER]
    return "".join(lines)


def main(argv=None) -> int:
    text = render()
    check = bool(argv) and argv[0] == "--check"
    if check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print("gui/Brand.cs is out of date; run python build/make_brand.py")
            return 1
        print("gui/Brand.cs matches the palette")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print("wrote %s" % TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
