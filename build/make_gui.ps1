<#
    Compile the two small Windows executables the product ships.

    .NET Framework 4.8 ships with every supported version of Windows, so the release
    carries no extra runtime for either of them and there is nothing to install to build
    them. csc.exe lives beside the framework itself.

    Every compiler argument is built as a complete string before the call. In argument
    mode PowerShell does not evaluate a parenthesised expression that is glued to a
    literal prefix - `/win32icon:(Join-Path ...)` is passed through verbatim, and csc
    then reports "Illegal characters in path".
#>
[CmdletBinding()]
param(
    [string]$Root,
    [string]$Out
)

$ErrorActionPreference = 'Stop'

# Resolved here rather than as parameter defaults. $PSScriptRoot is empty while defaults
# are bound and only populated once the body starts, so `Split-Path -Parent $PSScriptRoot`
# as a default throws under `powershell -File build/make_gui.ps1` - which is exactly how
# CONTRIBUTING.md tells a contributor to run this. Invoked as a command it happened to
# work, and the release workflow invokes it as a command, so the only broken route was
# the documented one.
if (-not $Root) { $Root = Split-Path -Parent $PSScriptRoot }
if (-not $Out)  { $Out  = Join-Path $Root 'build' }

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { throw 'The in-box C# compiler was not found.' }
# Recorded because reproducing a release needs the same compiler build: two builds of
# the in-box csc can emit different IL for the same source.
$cscVersion = (Get-Item $csc).VersionInfo.FileVersion
Write-Host ('compiler ' + $csc + ' ' + $cscVersion)

# The release build needs Python anyway (make_release.py); this needs it to make the
# executables reproducible.
$python = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $python) { throw 'Python is needed to make the build reproducible (build/normalize_pe.py).' }
$normalizer = Join-Path $Root 'build\normalize_pe.py'

# A version resource, generated from the manifest. Without one both executables said
# 0.0.0.0 with no product or publisher in Explorer's Properties and in SmartScreen and
# Smart App Control prompts - the places a person looks to decide whether to trust a file.
# The in-box compiler builds the Win32 version resource from these attributes, and the
# text is a pure function of the manifest, so the build stays reproducible.
$pluginManifest = Get-Content (Join-Path $Root '.codex-plugin\plugin.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$version = [string]$pluginManifest.version
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw ('plugin.json version is not MAJOR.MINOR.PATCH: ' + $version) }
$publisher = [string]$pluginManifest.author.name
$product = [string]$pluginManifest.interface.displayName
function Get-VersionInfoSource([string]$Description) {
    # Values are escaped for a C# string literal; the manifest is ours, but a quote in a
    # display name must not become a compile error, let alone code.
    function Lit([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }
    @(
        '// Generated by build/make_gui.ps1 from .codex-plugin/plugin.json. Do not edit.',
        'using System.Reflection;',
        ('[assembly: AssemblyTitle(' + (Lit $Description) + ')]'),
        ('[assembly: AssemblyDescription(' + (Lit $Description) + ')]'),
        ('[assembly: AssemblyProduct(' + (Lit $product) + ')]'),
        ('[assembly: AssemblyCompany(' + (Lit $publisher) + ')]'),
        ('[assembly: AssemblyCopyright(' + (Lit ('Copyright (c) ' + $publisher + '. MIT License.')) + ')]'),
        ('[assembly: AssemblyVersion("' + $version + '.0")]'),
        ('[assembly: AssemblyFileVersion("' + $version + '.0")]'),
        ('[assembly: AssemblyInformationalVersion("' + $version + '")]')
    ) -join "`r`n"
}

New-Item -ItemType Directory -Force $Out | Out-Null

$icon     = Join-Path $Root 'assets\codex-auto-resume.ico'
$manifest = Join-Path $Root 'gui\app.manifest'

function Build {
    param(
        [string]$Name,
        [string[]]$Sources,
        [string]$Target,
        [string[]]$References,
        [string]$Description,
        [switch]$WithManifest
    )
    $exe = Join-Path $Out $Name
    $versionInfo = Join-Path $Out ($Name + '.VersionInfo.cs')
    [IO.File]::WriteAllText($versionInfo, (Get-VersionInfoSource $Description), (New-Object Text.UTF8Encoding $false))
    $Sources = @($Sources) + @($versionInfo)
    $arguments = @('/nologo', ('/target:' + $Target), '/platform:x64', '/optimize+',
                   ('/out:' + $exe))
    foreach ($reference in $References) { $arguments += ('/reference:' + $reference) }
    if (Test-Path $icon) { $arguments += ('/win32icon:' + $icon) }
    # Only the window declares per-monitor DPI awareness; the launcher draws nothing.
    if ($WithManifest -and (Test-Path $manifest)) { $arguments += ('/win32manifest:' + $manifest) }
    $arguments += $Sources
    & $csc @arguments
    if ($LASTEXITCODE -ne 0) { throw ($Name + ' failed to compile.') }
    # The in-box compiler has no /deterministic: every build stamps the wall-clock second
    # into the PE header and a fresh random GUID into the module's metadata, and nothing
    # else varies. normalize_pe.py fixes both after the fact, so the same source always
    # produces the same bytes and anyone can rebuild a release and compare digests.
    & $python $normalizer $exe | Out-Null
    if ($LASTEXITCODE -ne 0) { throw ($Name + ' could not be made reproducible.') }
    $digest = (Get-FileHash $exe -Algorithm SHA256).Hash.ToLower()
    Write-Host ('built ' + $exe + ' (' + (Get-Item $exe).Length + ' bytes, sha256 ' + $digest + ')')
}

# Brand.cs is generated by build/make_brand.py from the Python palette, so the window
# and the Codex panel cannot end up different colours.
Build -Name 'CodexAutoResumeSettings.exe' -Target 'winexe' -WithManifest `
      -Description 'Codex Auto Resume settings' `
      -Sources @((Join-Path $Root 'gui\SettingsApp.cs'), (Join-Path $Root 'gui\Brand.cs')) `
      -References @('System.dll', 'System.Drawing.dll', 'System.Windows.Forms.dll')

# A console-subsystem executable on purpose: it inherits Codex's standard streams and
# hands them straight to the MCP server, which is the whole reason it exists.
Build -Name 'codex-auto-resume-mcp.exe' -Target 'exe' `
      -Description 'Codex Auto Resume MCP launcher' `
      -Sources @((Join-Path $Root 'gui\McpLauncher.cs')) `
      -References @('System.dll')
