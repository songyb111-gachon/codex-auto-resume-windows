fn day_look_method() -> Py<Vec<String>> {
    let [red, green, blue] = rgb(ICON_ACCENT.s())?;
    let mut lines = vec![
        format!(
            "        internal static Color IconHead() {{ return Color.FromArgb(0x{}, 0x{}, 0x{}); }}\n\n",
            crate::colour::hex2(red),
            crate::colour::hex2(green),
            crate::colour::hex2(blue)
        ),
        "        /// brand.day_look: the look of a date, its body top and bottom; false for an ordinary day.\n".to_owned(),
        "        internal static bool DayLook(int year, int month, int day, out string look, out string top, out string bottom)\n".to_owned(),
        "        {\n".to_owned(),
        "            int yearly = month * 100 + day, whole = year * 10000 + yearly;\n".to_owned(),
    ];
    let answer = |key: &str| {
        let look = days::DAY_LOOKS.at(key).list();
        format!(
            "{{ look = \"{key}\"; top = \"{}\"; bottom = \"{}\"; return true; }}",
            look[0].s(),
            look[1].s()
        )
    };
    for fixed in days::FIXED_DAYS.list() {
        let parts = fixed.list();
        lines.push(format!(
            "            if (yearly == {}) {}\n",
            parts[0].i() * 100 + parts[1].i(),
            answer(parts[2].s())
        ));
    }
    for entry in days::LUNAR_DAYS.list() {
        let parts = entry.list();
        let tests: Vec<String> = parts[1]
            .list()
            .iter()
            .map(|date| {
                let ymd = date.list();
                format!(
                    "whole == {}",
                    ymd[0].i() * 10000 + ymd[1].i() * 100 + ymd[2].i()
                )
            })
            .collect();
        lines.push(format!(
            "            if ({}) {}\n",
            tests.join(" || "),
            answer(parts[0].s())
        ));
    }
    lines.push("            look = top = bottom = null;\n".to_owned());
    lines.push("            return false;\n".to_owned());
    lines.push("        }\n\n".to_owned());
    for (name, tone) in [
        ("IconTopColour", ICON_TOP.s()),
        ("IconBottomColour", ICON_BOTTOM.s()),
        ("IconMarkColour", ICON_MARK.s()),
    ] {
        let [red, green, blue] = rgb(tone)?;
        lines.push(format!(
            "        internal static Color {name}() {{ return Color.FromArgb(0x{}, 0x{}, 0x{}); }}\n",
            crate::colour::hex2(red),
            crate::colour::hex2(green),
            crate::colour::hex2(blue)
        ));
    }
    lines.push("\n".to_owned());
    lines.push("        internal static double DayFocus(string look)\n".to_owned());
    lines.push("        {\n".to_owned());
    for (key, focus) in days::SCENE_FOCUS.items() {
        lines.push(format!(
            "            if (look == \"{key}\") return {};\n",
            pyfmt::g(focus.f())
        ));
    }
    lines.push("            return 0;\n".to_owned());
    lines.push("        }\n\n".to_owned());
    lines.push("        internal static bool DayFromTop(string look)\n".to_owned());
    lines.push("        {\n".to_owned());
    let from_top: Vec<String> = days::SCENE_FROM_TOP
        .strs()
        .map(|key| format!("look == \"{key}\""))
        .collect();
    lines.push(format!("            return {};\n", from_top.join(" || ")));
    lines.push("        }\n\n".to_owned());
    lines.push("        /// The scene's ground, and the body top and bottom.\n".to_owned());
    lines.push("        internal static void DayGround(string look, out string ground, out string top, out string bottom)\n".to_owned());
    lines.push("        {\n".to_owned());
    for (key, look) in days::DAY_LOOKS.items() {
        let parts = look.list();
        lines.push(format!(
            "            if (look == \"{key}\") {{ ground = \"{}\"; top = \"{}\"; bottom = \"{}\"; return; }}\n",
            parts[2].s(),
            parts[0].s(),
            parts[1].s()
        ));
    }
    lines.push("            ground = top = bottom = null;\n".to_owned());
    lines.push("        }\n\n".to_owned());
    let texts: [(&str, TextOf); 3] = [
        ("DayScene", days::scene_text),
        ("DaySpecks", days::speck_text),
        ("DayMark", days::mark_text),
    ];
    for (index, (name, text_of)) in texts.iter().enumerate() {
        lines.push(format!(
            "        internal static string {name}(string look)\n"
        ));
        lines.push("        {\n".to_owned());
        for key in days::DAY_LOOKS.keys() {
            lines.push(format!(
                "            if (look == \"{key}\") return \"{}\";\n",
                text_of(key)?.replace('\n', "\\n")
            ));
        }
        lines.push("            return \"\";\n".to_owned());
        lines.push(
            if index + 1 < texts.len() {
                "        }\n\n"
            } else {
                "        }\n"
            }
            .to_owned(),
        );
    }
    Ok(lines)
}

