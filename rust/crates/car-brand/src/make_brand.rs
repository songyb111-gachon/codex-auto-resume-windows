fn colours(theme: &str, indent: &str, design: &str) -> Py<Vec<String>> {
    let tokens = tokens::palette(Some(theme), Some(design))?;
    let mut rows: Vec<(&str, String, &str)> = FIELDS
        .iter()
        .map(|(name, token, note)| (*name, tokens.at(token).s().to_owned(), *note))
        .collect();
    for (name, note) in DERIVED {
        rows.push((
            name,
            elevation::card_ground(Some(theme), Some(design))?,
            note,
        ));
    }
    let width = rows
        .iter()
        .map(|(name, _, _)| name.chars().count())
        .max()
        .unwrap_or(0);
    let mut lines = Vec::new();
    for (name, value, note) in rows {
        let [red, green, blue] = rgb(&value)?;
        lines.push(format!(
            "{indent}internal static readonly Color {name:<width$} = Color.FromArgb(0x{}, 0x{}, 0x{});  // {value}, {note}\n",
            crate::colour::hex2(red),
            crate::colour::hex2(green),
            crate::colour::hex2(blue)
        ));
    }
    Ok(lines)
}

/// `_nested`: a member written for Brand, indented one level further.
fn nested(text: &str) -> String {
    text.split_inclusive('\n')
        .map(|line| {
            if line.trim().is_empty() {
                line.to_owned()
            } else {
                format!("    {line}")
            }
        })
        .collect()
}

