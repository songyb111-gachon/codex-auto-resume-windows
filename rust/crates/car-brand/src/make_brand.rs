fn camel(key: &str) -> String {
    key.split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// One constant's value as `_literal` reads it.
#[derive(Clone, Copy, Debug)]
enum Lit {
    Bool(bool),
    N(Num),
}

fn literal(kind: &str, value: Lit) -> Py<String> {
    let number = match value {
        Lit::Bool(flag) => {
            if kind == "bool" {
                return Ok(if flag { "true" } else { "false" }.to_owned());
            }
            Num::I(i64::from(flag))
        }
        Lit::N(number) => {
            if kind == "bool" {
                return Err("ValueError");
            }
            number
        }
    };
    if kind == "int" {
        return match number {
            Num::I(int) => Ok(int.to_string()),
            Num::F(x) if x.fract() == 0.0 => Ok(pyfmt::d(x)),
            Num::F(_) => Err("ValueError"),
        };
    }
    let x = number.f();
    let text = if x.fract() == 0.0 && x.is_finite() {
        pyfmt::d(x)
    } else {
        pyfmt::repr(pyfmt::round_to(x, 6))
    };
    Ok(if kind == "float" { text + "f" } else { text })
}

fn int(value: i64) -> Lit {
    Lit::N(Num::I(value))
}

fn double(value: f64) -> Lit {
    Lit::N(Num::F(value))
}

fn num(value: &D) -> Lit {
    Lit::N(value.n())
}

fn colour_literal(rgb: [i64; 3]) -> String {
    format!(
        "Color.FromArgb(0x{}, 0x{}, 0x{})",
        crate::colour::hex2(rgb[0]),
        crate::colour::hex2(rgb[1]),
        crate::colour::hex2(rgb[2])
    )
}

fn field_of(token: &str) -> Py<&'static str> {
    FIELDS
        .iter()
        .find(|(_, each, _)| *each == token)
        .map(|(name, _, _)| *name)
        .ok_or("KeyError")
}

/// Values grouped by first appearance, each with the keys that give it, leaving out `fallback`.
fn grouped<'a>(
    pairs: impl Iterator<Item = (&'a str, &'a str)>,
    fallback: &str,
) -> Vec<(&'a str, Vec<&'a str>)> {
    let mut groups: Vec<(&str, Vec<&str>)> = Vec::new();
    for (key, value) in pairs {
        if value == fallback {
            continue;
        }
        match groups.iter_mut().find(|(each, _)| *each == value) {
            Some((_, keys)) => keys.push(key),
            None => groups.push((value, vec![key])),
        }
    }
    groups
}

fn condition(states: &[&str]) -> String {
    states
        .iter()
        .map(|state| format!("state == \"{state}\""))
        .collect::<Vec<_>>()
        .join(" || ")
}

