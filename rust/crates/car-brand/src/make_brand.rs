/// Whether a design has colours of its own, rather than Soft's (`_own_colours`).
fn own_colours(design: &str) -> bool {
    let ours = t::DESIGN_TOKENS.at(design).list();
    let soft = t::DESIGN_TOKENS.at(DEFAULT_DESIGN.s()).list();
    !(ours[0].s() == soft[0].s() && ours[1].s() == soft[1].s())
}

fn design_rules() -> Py<String> {
    let default = DEFAULT_DESIGN.s();
    let designs: Vec<&str> = DESIGNS.strs().collect();
    if !designs.contains(&default) {
        return Err("ValueError");
    }
    let mut lines: Vec<String> = vec![
        format!(
            "        /// A stored Design (v0.6.10) as the settings layer reads it: \"{}\" exactly, and \"{default}\" for\n",
            designs.join("\", \"")
        ),
        "        /// anything else - a missing value, another case, another type.\n".to_owned(),
        "        internal static string DesignOf(object value)\n".to_owned(),
        "        {\n".to_owned(),
        "            string text = value as string;\n".to_owned(),
        format!(
            "            if ({}) return text;\n",
            designs
                .iter()
                .map(|name| format!("text == \"{name}\""))
                .collect::<Vec<_>>()
                .join(" || ")
        ),
        "            return DesignDefault;\n".to_owned(),
        "        }\n".to_owned(),
        "\n".to_owned(),
        format!(
            "        /// The design whose colours a design draws in: its own, or {default}'s (brand.DESIGN_TOKENS).\n"
        ),
        "        internal static string DesignColours(string design)\n".to_owned(),
        "        {\n".to_owned(),
    ];
    for name in designs.iter().filter(|name| own_colours(name)) {
        lines.push(format!(
            "            if (design == \"{name}\") return \"{name}\";\n"
        ));
    }
    lines.push("            return DesignDefault;\n".to_owned());
    lines.push("        }\n".to_owned());
    for (rule, axis, meaning) in DESIGN_RULES {
        let answer = DESIGN.at(default).at(axis).b();
        let other: Vec<&str> = designs
            .iter()
            .copied()
            .filter(|name| DESIGN.at(name).at(axis).b() != answer)
            .collect();
        lines.push("\n".to_owned());
        lines.push(format!(
            "        /// Whether a design {meaning} (brand.DESIGN's {axis}).\n"
        ));
        lines.push(format!(
            "        internal static bool {rule}(string design)\n"
        ));
        lines.push("        {\n".to_owned());
        if !other.is_empty() {
            lines.push(format!(
                "            if ({}) return {};\n",
                other
                    .iter()
                    .map(|name| format!("design == \"{name}\""))
                    .collect::<Vec<_>>()
                    .join(" || "),
                if !answer { "true" } else { "false" }
            ));
        }
        lines.push(format!(
            "            return {};\n",
            if answer { "true" } else { "false" }
        ));
        lines.push("        }\n".to_owned());
    }
    let roles: Vec<&str> = RADII.keys().collect();
    let radius = |design: &str, role: &str| DESIGN_RADII.at(design).at(role).n();
    let same = |one: &str, other: &str| {
        let (a, b) = (DESIGN_RADII.at(one).items(), DESIGN_RADII.at(other).items());
        a.len() == b.len()
            && a.iter().all(|(key, value)| {
                DESIGN_RADII.at(other).find(key).is_some_and(|each| {
                    each.n().compare(value.n()) == Some(std::cmp::Ordering::Equal)
                })
            })
    };
    for name in &designs {
        if DESIGN_RADII.at(name).keys().collect::<Vec<_>>() != roles {
            return Err("ValueError");
        }
        if roles
            .iter()
            .any(|role| radius(name, role).gt(radius(default, role)))
        {
            return Err("ValueError");
        }
    }
    lines.push("\n".to_owned());
    lines.push(format!(
        "        /// A design's corner radius for one of brand.RADII's roles (\"{}\"), in CSS px\n",
        roles.join("\", \"")
    ));
    lines.push(format!("        /// (brand.DESIGN_RADII) - never larger than {default}'s. 0 for a role there is none of.\n"));
    lines.push("        internal static int DesignRadius(string design, string role)\n".to_owned());
    lines.push("        {\n".to_owned());
    for name in &designs {
        if *name == default || same(name, default) {
            continue;
        }
        lines.push(format!("            if (design == \"{name}\")\n"));
        lines.push("            {\n".to_owned());
        for role in &roles {
            lines.push(format!(
                "                if (role == \"{role}\") return {};\n",
                literal("int", Lit::N(radius(name, role)))?
            ));
        }
        lines.push("                return 0;\n".to_owned());
        lines.push("            }\n".to_owned());
    }
    for role in &roles {
        lines.push(format!(
            "            if (role == \"{role}\") return {};\n",
            literal("int", Lit::N(radius(default, role)))?
        ));
    }
    lines.push("            return 0;\n".to_owned());
    lines.push("        }\n".to_owned());
    lines.extend(
        [
            "\n",
            "        /// v0.6.24: how much a design smooths its corners (brand/shape.py's DESIGN_SMOOTHING): Figma's corner\n",
            "        /// smoothing, a share of the radius; 0 is the circular corner.\n",
            "        internal static double DesignSmoothing(string design)\n",
            "        {\n",
        ]
        .map(str::to_owned),
    );
    let smoothing = |design: &str| DESIGN_SMOOTHING.at(design).n();
    for name in &designs {
        if smoothing(name).compare(smoothing(default)) != Some(std::cmp::Ordering::Equal) {
            lines.push(format!(
                "            if (design == \"{name}\") return {};\n",
                literal("double", Lit::N(smoothing(name)))?
            ));
        }
    }
    lines.push(format!(
        "            return {};\n",
        literal("double", Lit::N(smoothing(default)))?
    ));
    lines.extend(
        [
            "        }\n",
            "\n",
            "        /// One design in one theme (Brand.Look): `design` as DesignOf reads it, dark or light. What the window\n",
            "        /// adopts, and the one question it asks about a design, so none of its own code names one.\n",
            "        internal static Look LookOf(string design, bool dark)\n",
            "        {\n",
            "            return new Look(design, dark);\n",
            "        }\n",
        ]
        .map(str::to_owned),
    );
    Ok(lines.concat())
}

