fn check_condition(states: &[&str]) -> String {
    let of = |state: &str| {
        CHECK_CONDITIONS
            .iter()
            .find(|(each, _)| *each == state)
            .map_or("", |(_, text)| text)
    };
    if states.len() == 1 {
        return of(states[0]).to_owned();
    }
    states
        .iter()
        .map(|state| format!("({})", of(state)))
        .collect::<Vec<_>>()
        .join(" || ")
}

fn check_rule(
    table: &'static D,
    part: &str,
    name_of: &dyn Fn(&str) -> Py<String>,
) -> Py<Vec<String>> {
    let fallback = name_of(table.at("off_disabled").at(part).s())?;
    let mut groups: Vec<(String, Vec<&str>)> = Vec::new();
    for (state, entry) in table.items() {
        let name = name_of(entry.at(part).s())?;
        if name != fallback {
            match groups.iter_mut().find(|(each, _)| *each == name) {
                Some((_, states)) => states.push(state),
                None => groups.push((name, vec![state])),
            }
        }
    }
    let mut lines: Vec<String> = groups
        .iter()
        .map(|(name, states)| {
            format!(
                "            if ({}) return {name};\n",
                check_condition(states)
            )
        })
        .collect();
    lines.push(format!("            return {fallback};\n"));
    Ok(lines)
}

