/// `mark_frames(size)`: one size's frames as the window reads them (MarkFrames in gui/Marks.cs).
pub fn mark_frames(size: i64) -> Py<Vec<u8>> {
    let frames = IconFrames::new(size, 1, None)?;
    let ground = &frames.ground;
    let mut out = Vec::new();
    let mut start = 0;
    while start < ground.len() {
        let pixel = &ground[start..start + 4];
        let mut count = 1;
        while count < 255 && ground.get(start + 4 * count..start + 4 * count + 4) == Some(pixel) {
            count += 1;
        }
        out.push(count as u8);
        out.extend_from_slice(pixel);
        start += 4 * count;
    }
    let whole = ICON_SUPERSAMPLE.i() * ICON_SUPERSAMPLE.i();
    for (bounds, rows) in &frames.heads {
        let [left, top, right, bottom] = *bounds;
        for part in [left, top, right, bottom] {
            out.push(u8::try_from(part).map_err(|_| "ValueError")?);
        }
        for (y, row) in rows.iter().enumerate() {
            for (x, sample) in row.iter().enumerate() {
                let [covered, heads, red, green, blue] = *sample;
                if heads == 0 {
                    let index = (((top + y as i64) * size + left + x as i64) * 4) as usize;
                    let [r, g, b, alpha] = icon_pixel(sample, [0, 0, 0]);
                    if [b, g, r, alpha]
                        .iter()
                        .map(|each| *each as u8)
                        .collect::<Vec<_>>()
                        != ground[index..index + 4]
                    {
                        return Err("ValueError");
                    }
                    out.push(MARK_GROUND);
                } else if covered == heads && heads == whole {
                    out.push(MARK_HEAD);
                } else {
                    out.push(MARK_SAMPLES);
                    out.push(u8::try_from(covered).map_err(|_| "ValueError")?);
                    out.push(u8::try_from(heads).map_err(|_| "ValueError")?);
                    for value in [red, green, blue] {
                        out.extend_from_slice(
                            &u16::try_from(value).map_err(|_| "error")?.to_le_bytes(),
                        );
                    }
                }
            }
        }
    }
    let accent = rgb(ICON_ACCENT.s())?;
    for position in 0..ICON_MOTION.at("positions").i() {
        for colour in [accent, [0, 0, 0], [255, 255, 255], [201, 7, 99]] {
            if mark_compose(&out, size, position, colour)? != frames.compose(position, colour)? {
                return Err("ValueError");
            }
        }
    }
    Ok(out)
}

/// `mark_compose(data, size, position, head)`: one frame read back from mark_frames' bytes, top-down BGRA.
pub fn mark_compose(data: &[u8], size: i64, position: i64, head: [i64; 3]) -> Py<Vec<u8>> {
    let total = (size * size * 4) as usize;
    let mut pixels: Vec<u8> = Vec::with_capacity(total);
    let mut at = 0;
    let byte = |index: usize| data.get(index).copied().ok_or("IndexError");
    while pixels.len() < total {
        let count = byte(at)? as usize;
        let pixel = data.get(at + 1..at + 5).ok_or("IndexError")?;
        for _ in 0..count {
            pixels.extend_from_slice(pixel);
        }
        at += 5;
    }
    if pixels.len() != total {
        return Err("ValueError");
    }
    let whole = ICON_SUPERSAMPLE.i() * ICON_SUPERSAMPLE.i();
    for index in 0..ICON_MOTION.at("positions").i() {
        let (left, top, right, bottom) = (byte(at)?, byte(at + 1)?, byte(at + 2)?, byte(at + 3)?);
        at += 4;
        for y in top as i64..bottom as i64 {
            for x in left as i64..right as i64 {
                let kind = byte(at)?;
                at += 1;
                if kind == MARK_GROUND {
                    continue;
                }
                let sample = if kind == MARK_HEAD {
                    [whole, whole, 0, 0, 0]
                } else {
                    let word = |offset: usize| -> Py<i64> {
                        Ok(i64::from(u16::from_le_bytes([
                            byte(offset)?,
                            byte(offset + 1)?,
                        ])))
                    };
                    let found = [
                        i64::from(byte(at)?),
                        i64::from(byte(at + 1)?),
                        word(at + 2)?,
                        word(at + 4)?,
                        word(at + 6)?,
                    ];
                    at += 8;
                    found
                };
                if index != position {
                    continue;
                }
                let offset = ((y * size + x) * 4) as usize;
                let pixel = icon_pixel(&sample, head);
                let bytes = [pixel[2], pixel[1], pixel[0], pixel[3]]
                    .map(|each| u8::try_from(each).map_err(|_| "ValueError"));
                for (step, value) in bytes.into_iter().enumerate() {
                    pixels[offset + step] = value?;
                }
            }
        }
    }
    if at != data.len() {
        return Err("ValueError");
    }
    Ok(pixels)
}

/// Standard base64 with padding (`base64.b64encode`).
pub fn base64(data: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let bits = (u32::from(chunk[0]) << 16)
            | (u32::from(*chunk.get(1).unwrap_or(&0)) << 8)
            | u32::from(*chunk.get(2).unwrap_or(&0));
        for index in 0..4 {
            if index <= chunk.len() {
                out.push(ALPHABET[((bits >> (18 - 6 * index)) & 63) as usize] as char);
            } else {
                out.push('=');
            }
        }
    }
    out
}

