"""Generate the Unicode table car-codex and car-platform read, from the reference Python's own `str.isprintable`.

    python -X utf8 tests/rustdiff/gen_codex.py --write | --check

`labels._label` keeps only the characters Python calls printable (every code point but those of the general
categories Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs, a plain space excepted): Rust's `char` has no such question, and
the interpreter's Unicode version decides it. The table is made by the Python the product ships (build/make_release.py
PYTHON_VERSION, 3.14.10: Unicode 16.0.0; productpy.py runs this script under it, the file says which Python and
`unicodedata` made it, and --check refuses a file made by any other) and `diffs_codex_readers.py` asks both sides about every one of the 1,114,112 code points. car-platform
reads the same table for `repr()` (addremove.display_name's `str()` of a list or a dict, review 4 note 5): the two
files are one table, written and checked together.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))  # the embeddable runtime has no script directory on its path
import productpy  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "rust" / "crates" / "car-codex" / "src" / "printable_gen.rs"
TARGETS = (TARGET, ROOT / "rust" / "crates" / "car-platform" / "src" / "printable_gen.rs")


def ranges(points):
    found, start, last = [], None, None
    for point in points:
        if start is None:
            start = last = point
        elif point == last + 1:
            last = point
        else:
            found.append((start, last))
            start = last = point
    if start is not None:
        found.append((start, last))
    return found


def render() -> str:
    pairs = ranges(point for point in range(0x110000) if chr(point).isprintable())
    return "\n".join([
        "// Generated by tests/rustdiff/gen_codex.py from `str.isprintable` of %s. Do not edit." % productpy.stamp(),
        "/// The code points `str.isprintable()` is true of, as inclusive ranges (a surrogate is none of them).",
        "pub static PRINTABLE: &[(u32, u32)] = &[%s];" % ", ".join("(0x%X, 0x%X)" % pair for pair in pairs),
        ""])


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    ran = productpy.ensure(__file__, sys.argv[1:] if argv is None else argv)
    if ran is not None:
        return ran
    text = render()
    stale = 0
    for target in TARGETS:
        if args.write:
            target.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", target.relative_to(ROOT).as_posix())
            continue
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        refused = productpy.stale(current, target.relative_to(ROOT).as_posix())
        if refused or current != text:
            print(refused or "stale: %s (run gen_codex.py --write)" % target.relative_to(ROOT).as_posix())
            stale = 1
        else:
            print("current:", target.relative_to(ROOT).as_posix())
    return stale


if __name__ == "__main__":
    sys.exit(main())
