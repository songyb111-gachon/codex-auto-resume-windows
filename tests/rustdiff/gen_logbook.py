"""Generate car-config's logbook tables (the sentences of `logbook._MESSAGES` and `SKIP_WORDS`) from the reference tag.

    python -X utf8 tests/rustdiff/gen_logbook.py --write | --check

The log's lines are pinned (Diagnostics and `ownreport` read them back), so the table of sentences is the tag's, copied as
data. The diff (diffs_leaves_config.py) renders every (code, reason) pair through both and compares the lines.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "rust" / "crates" / "car-config" / "src" / "logbook_gen.rs"
SCRIPT = r'''
import json
from codex_auto_resume import logbook
print(json.dumps({"messages": [[code, reason, text] for (code, reason), text in logbook._MESSAGES.items()],
                  "skip_words": [[code, text] for code, text in logbook.SKIP_WORDS.items()]}))
'''


def literal(value) -> str:
    return "None" if value is None else "Some(%s)" % json.dumps(value, ensure_ascii=False)


def generate(tag: str) -> str:
    sys.path[:] = [entry for entry in sys.path if Path(entry or ".").resolve() != Path(__file__).resolve().parent]
    sys.path[:0] = [str(ROOT / "src"), str(ROOT / "tests")]
    from rustdiff import reference  # the reference's Python (`--reference-python`), not released.run's sys.executable
    ran = reference.run(SCRIPT, tag=tag)
    if ran.returncode != 0:
        raise SystemExit(ran.stderr.decode("utf-8", "replace")[-3000:])
    done = json.loads(ran.stdout.decode("utf-8"))
    lines = ["// Generated by tests/rustdiff/gen_logbook.py from the reference tag's logbook.py. Do not edit.",
             "/// `_MESSAGES`: (state or code, reason or none, the sentence), in the order the Python lists them.",
             "pub static MESSAGES: &[(&str, Option<&str>, &str)] = &["]
    for code, reason, text in done["messages"]:
        lines.append("    (%s, %s, %s)," % (json.dumps(code), literal(reason), json.dumps(text, ensure_ascii=False)))
    lines.append("];")
    lines.append("/// `SKIP_WORDS`: why a failed turn was not taken up, by the code written in the log.")
    lines.append("pub static SKIP_WORDS: &[(&str, &str)] = &[")
    for code, text in done["skip_words"]:
        lines.append("    (%s, %s)," % (json.dumps(code), json.dumps(text, ensure_ascii=False)))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    sys.path.insert(0, str(ROOT / "tests"))
    from rustdiff import reference
    text = generate(reference.TAG)
    if args.write:
        TARGET.write_bytes(text.encode("utf-8"))
        return 0
    if not TARGET.is_file() or TARGET.read_bytes().decode("utf-8") != text:
        print("%s differs from %s's logbook: run gen_logbook.py --write" % (TARGET.relative_to(ROOT), reference.TAG))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
