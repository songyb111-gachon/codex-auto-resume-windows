"""Generate car-policy's data from the reference: the classifier half's (S2.1) and the settings and plug half's (S2.2), each
the closed vocabularies of the Python modules it ports and the Python text tables its rules read.

    python -X utf8 tests/rustdiff/gen_policy.py --write              # write the five generated files
    python -X utf8 tests/rustdiff/gen_policy.py --check              # fail when a file differs from what the tag gives
    python -X utf8 tests/rustdiff/gen_policy.py --check --ref v0.6.26

Two files, under rust/crates/car-policy/src/classify/ (S2.1):

    vocab_gen.rs    every enum and word list of the Python modules S2.1 ports (MINE), from `build/vocab_export.py
                    --ref <tag>`'s vocab.json, in the shape gen_vocab.py gives car-machine's (`module_source`), with a
                    MODULES table whose `export()` diffs_classify_vocab.py compares with the tag's
    text_tables.rs  what the classifier asks of Python's own `str`: `str.lower()` and `str.casefold()` for every code point
                    they change, and
                    the code points `re`'s `\\w` matches in a str pattern - made by this interpreter, whose Unicode
                    version the file names (the bundled Python's, 3.13: Unicode 15.1)

Three more, from S2.2, under rust/crates/car-policy/src/settings/ and src/plug/:

    settings/vocab_gen.rs   settings, managed, ownvalues, homes, notice_kinds, poweraction, statusfile, demo
    plug/vocab_gen.rs       domain.plug, domain.plugwords, domain.plughands, edition
    settings/unicode_gen.rs `str.casefold()` for every code point it changes (homes' aliases) and the code points
                            `str.isalnum()` is true of (the status file's version)

`--check` is the one command that says whether the port still matches a tag's vocabulary: rerun it with `--ref` the
final tag (and tests/rustdiff/rediff_classify.py runs it beside the diffs; the behaviour itself is held by
`tests/rustdiff/run.py -k Settings -k Plug -k Policy`, diffs_settings_*.py).
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys
import unicodedata

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FOLDER = ROOT / "rust" / "crates" / "car-policy" / "src" / "classify"
VOCAB = FOLDER / "vocab_gen.rs"
TABLES = FOLDER / "text_tables.rs"
POLICY = ROOT / "rust" / "crates" / "car-policy" / "src"

# The Python modules this seat ports, in the order their file lists them.
MINE = ("failures", "reasons", "domain.gates", "guards", "ladder", "quiet", "projects", "needsyou", "power",
        "continuation", "compat.permits")


# S2.2: the modules it ports, and the file each one's vocabulary goes to.
SETTINGS = ("settings", "managed", "ownvalues", "homes", "notice_kinds", "poweraction", "statusfile", "demo")
PLUG = ("domain.plug", "domain.plugwords", "domain.plughands", "edition")
TARGETS = {POLICY / "settings" / "vocab_gen.rs": SETTINGS, POLICY / "plug" / "vocab_gen.rs": PLUG}
UNICODE = POLICY / "settings" / "unicode_gen.rs"


def _gen_vocab():
    sys.path.insert(0, str(HERE))
    try:
        import gen_vocab
    finally:
        sys.path.pop(0)
    return gen_vocab


def vocab_file(vocab: dict) -> str:
    gen = _gen_vocab()
    parts = [
        "// Generated by tests/rustdiff/gen_policy.py from `build/vocab_export.py --ref <tag>`'s vocab.json. Do not edit:",
        "// `gen_policy.py --check` regenerates it and compares, and diffs_classify_vocab.py compares `export()` with the tag's.",
        "#![allow(dead_code, unused_imports, clippy::all)]",
        "use car_machine::vocab::{Const, EnumDef, ModuleDef, Node};",
        "",
    ]
    defs = []
    for name in MINE:
        source, definition = gen.module_source(name, vocab["modules"][name])
        parts += [source, ""]
        defs.append("    %s," % definition)
    parts += ["/// Every module S2.1 ports, as the exporter writes it.", "pub static MODULES: &[ModuleDef] = &["]
    parts += defs + ["];", ""]
    return "\n".join(parts)


def _vocab_file(names, vocab) -> str:
    """S2.2's vocabulary files: the modules `names`, in the same form as `vocab_file`."""
    gen = _gen_vocab()
    parts = [
        "// Generated by tests/rustdiff/gen_policy.py from `build/vocab_export.py --ref <tag>`'s vocab.json. Do not edit:",
        "// `gen_policy.py --check` regenerates it and compares; diffs_settings_vocab compares `export()` with the tag's.",
        "#![allow(dead_code, unused_imports, clippy::all)]",
        "use car_machine::vocab::{Const, EnumDef, ModuleDef, Node};",
        "",
    ]
    defs = []
    for name in names:
        source, definition = gen.module_source(name, vocab["modules"][name])
        parts += [source, ""]
        defs.append("    %s," % definition)
    parts += ["/// Every module of this file's Python, as the exporter writes it.", "pub static MODULES: &[ModuleDef] = &["]
    parts += defs + ["];", ""]
    return "\n".join(parts)


def _unicode_file() -> str:
    """S2.2's `settings/unicode_gen.rs`: `str.casefold()` and `str.isalnum()` of this interpreter."""
    folds, alnum = [], []
    for point in range(0x110000):
        c = chr(point)
        folded = c.casefold()
        if folded != c:
            folds.append((point, folded))
        if c.isalnum():
            alnum.append(point)
    ranges = []
    for point in alnum:
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])

    def text(value: str) -> str:
        return '"%s"' % "".join("\\u{%X}" % ord(each) for each in value)

    lines = [
        "// Generated by tests/rustdiff/gen_policy.py from Python %s's `str` (unicodedata %s). Do not edit."
        % (".".join(map(str, sys.version_info[:3])), unicodedata.unidata_version),
        "/// `str.casefold()` of every code point it changes, by code point.",
        "pub static CASEFOLD: &[(u32, &str)] = &[%s];" % ", ".join("(0x%X, %s)" % (point, text(folded))
                                                                     for point, folded in folds),
        "/// The code points `str.isalnum()` is true of, as inclusive ranges.",
        "pub static ALNUM: &[(u32, u32)] = &[%s];" % ", ".join("(0x%X, 0x%X)" % (low, high) for low, high in ranges),
        "",
    ]
    return "\n".join(lines)


def _ranges(points):
    out, start, last = [], None, None
    for point in points:
        if start is None:
            start = last = point
        elif point == last + 1:
            last = point
        else:
            out.append((start, last))
            start = last = point
    if start is not None:
        out.append((start, last))
    return out


def tables_file() -> str:
    word = re.compile(r"\w")
    lowered, folded, words = [], [], []
    for point in range(0x110000):
        if 0xD800 <= point < 0xE000:
            continue
        char = chr(point)
        if char.lower() != char:
            lowered.append((point, char.lower()))
        if char.casefold() != char:
            folded.append((point, char.casefold()))
        if word.match(char):
            words.append(point)
    lines = [
        "// Generated by tests/rustdiff/gen_policy.py from Python %s (Unicode %s). Do not edit: `gen_policy.py --check`"
        % (".".join(map(str, sys.version_info[:3])), unicodedata.unidata_version),
        "// regenerates it, and diffs_classify_vocab.py holds it to the reference's interpreter code point by code point.",
        "",
        "/// The Unicode version of the interpreter the tables were made by.",
        "pub const UNICODE: &str = %s;" % _rust_str(unicodedata.unidata_version),
        "",
        "/// `str.lower()` of each code point it changes: (code point, what it becomes), by code point.",
        "pub static LOWER: &[(u32, &str)] = &[%s];" % ", ".join(
            "(0x%X, %s)" % (point, _rust_str(text)) for point, text in lowered),
        "",
        "/// `str.casefold()` of each code point it changes, by code point.",
        "pub static FOLD: &[(u32, &str)] = &[%s];" % ", ".join(
            "(0x%X, %s)" % (point, _rust_str(text)) for point, text in folded),
        "",
        "/// The code points `re.compile(r\"\\w\")` matches in a str pattern, as inclusive ranges.",
        "pub static WORD: &[(u32, u32)] = &[%s];" % ", ".join("(0x%X, 0x%X)" % pair for pair in _ranges(words)),
        "",
    ]
    return "\n".join(lines)


def _rust_str(text: str) -> str:
    return '"%s"' % "".join(ch if 0x20 <= ord(ch) < 0x7F and ch not in '"\\' else "\\u{%x}" % ord(ch) for ch in text)


def generate(ref: str) -> dict:
    gen = _gen_vocab()
    vocab = gen.vocabulary(ref)
    files = {VOCAB: vocab_file(vocab), TABLES: tables_file()}
    files.update({path: _vocab_file(names, vocab) for path, names in TARGETS.items()})
    files[UNICODE] = _unicode_file()
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ref", default=None, help="the tag (default: rustdiff.reference.TAG)")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    ref = args.ref
    if ref is None:
        sys.path[:] = [entry for entry in sys.path if Path(entry or ".").resolve() != HERE]
        sys.path[:0] = [str(ROOT / "src"), str(ROOT / "tests")]
        from rustdiff import reference
        ref = reference.TAG
    status = 0
    for path, text in generate(ref).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
        elif not path.exists() or path.read_bytes().decode("utf-8") != text:
            print("%s differs from what %s gives: run gen_policy.py --write --ref %s" % (
                path.relative_to(ROOT).as_posix(), ref, ref))
            status = 1
    if status == 0 and not args.write:
        print("car-policy: generated files (classify, settings, plug) match %s" % ref)
    return status


if __name__ == "__main__":
    sys.exit(main())
