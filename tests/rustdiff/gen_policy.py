"""Generate car-policy's data of the S2.2 seat (settings and the plug), held to the reference tag.

    python -X utf8 tests/rustdiff/gen_policy.py --write      # write the generated files
    python -X utf8 tests/rustdiff/gen_policy.py --check      # fail when a file differs from what the tag gives
    python -X utf8 tests/rustdiff/gen_policy.py --check --ref v0.6.26

Two kinds of data, each from the reference (D17: the v0.6.26 tag; until it exists v0.6.26-beta.2,
`reference.STAND_IN`):

* the closed vocabularies of the modules this seat ports, from `build/vocab_export.py --ref TAG`'s vocab.json, in
  gen_vocab.py's own form (enums with `as_str`, `parse` and `ALL`; constants; a `MODULES` table `export()` writes back):

      rust/crates/car-policy/src/settings/vocab_gen.rs   settings, managed, ownvalues, homes, notice_kinds,
                                                         poweraction, statusfile, demo
      rust/crates/car-policy/src/plug/vocab_gen.rs       domain.plug, domain.plugwords, domain.plughands, edition

* Python's own text rules the settings and the status file use, from the interpreter that runs this script (the
  reference runs on the same CPython, 3.13): `str.casefold()` for every code point it changes (homes' aliases)
  and the code points `str.isalnum()` is true of (the status file's version):

      rust/crates/car-policy/src/settings/unicode_gen.rs

`--check` is the one command that says whether the final tag changed a word or a rule's data under the port; the
behaviour itself is held by `tests/rustdiff/run.py -k Settings -k Plug -k Policy` (diffs_settings_*.py).
"""
from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
POLICY = ROOT / "rust" / "crates" / "car-policy" / "src"

SETTINGS = ("settings", "managed", "ownvalues", "homes", "notice_kinds", "poweraction", "statusfile", "demo")
PLUG = ("domain.plug", "domain.plugwords", "domain.plughands", "edition")
TARGETS = {POLICY / "settings" / "vocab_gen.rs": SETTINGS, POLICY / "plug" / "vocab_gen.rs": PLUG}
UNICODE = POLICY / "settings" / "unicode_gen.rs"


def _vocab_file(names, vocab) -> str:
    from rustdiff import gen_vocab
    parts = [
        "// Generated by tests/rustdiff/gen_policy.py from `build/vocab_export.py --ref <tag>`'s vocab.json. Do not edit:",
        "// `gen_policy.py --check` regenerates it and compares; diffs_settings_vocab compares `export()` with the tag's.",
        "#![allow(dead_code, unused_imports, clippy::all)]",
        "use car_machine::vocab::{Const, EnumDef, ModuleDef, Node};",
        "",
    ]
    defs = []
    for name in names:
        source, definition = gen_vocab.module_source(name, vocab["modules"][name])
        parts += [source, ""]
        defs.append("    %s," % definition)
    parts += ["/// Every module of this file's Python, as the exporter writes it.", "pub static MODULES: &[ModuleDef] = &["]
    parts += defs + ["];", ""]
    return "\n".join(parts)


def _ranges(points) -> list:
    ranges = []
    for point in points:
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ranges


def _unicode_file() -> str:
    folds, alnum = [], []
    for point in range(0x110000):
        c = chr(point)
        folded = c.casefold()
        if folded != c:
            folds.append((point, folded))
        if c.isalnum():
            alnum.append(point)

    def text(value: str) -> str:
        return '"%s"' % "".join("\\u{%X}" % ord(each) for each in value)

    lines = [
        "// Generated by tests/rustdiff/gen_policy.py from Python %s's `str` (unicodedata %s). Do not edit."
        % (".".join(map(str, sys.version_info[:3])), unicodedata.unidata_version),
        "/// `str.casefold()` of every code point it changes, by code point.",
        "pub static CASEFOLD: &[(u32, &str)] = &[%s];" % ", ".join("(0x%X, %s)" % (point, text(folded))
                                                                     for point, folded in folds),
        "/// The code points `str.isalnum()` is true of, as inclusive ranges.",
        "pub static ALNUM: &[(u32, u32)] = &[%s];" % ", ".join("(0x%X, 0x%X)" % (low, high)
                                                               for low, high in _ranges(alnum)),
        "",
    ]
    return "\n".join(lines)


def generate(ref: str) -> dict:
    from rustdiff import gen_vocab
    vocab = gen_vocab.vocabulary(ref)
    files = {path: _vocab_file(names, vocab) for path, names in TARGETS.items()}
    files[UNICODE] = _unicode_file()
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ref", default=None, help="the tag (default: rustdiff.reference.TAG)")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    sys.path[:] = [entry for entry in sys.path if Path(entry or ".").resolve() != HERE]
    sys.path[:0] = [str(ROOT / "src"), str(ROOT / "tests")]
    ref = args.ref
    if ref is None:
        from rustdiff import reference
        ref = reference.TAG
    status = 0
    for path, text in generate(ref).items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
        elif not path.exists() or path.read_bytes().decode("utf-8") != text:
            print("%s differs from what %s gives: run gen_policy.py --write" % (path.relative_to(ROOT).as_posix(), ref))
            status = 1
    if status == 0 and not args.write:
        print("car-policy's generated data is %s's" % ref)
    return status


if __name__ == "__main__":
    sys.exit(main())
