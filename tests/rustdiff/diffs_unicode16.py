"""The Unicode tables follow the Python the product ships: 3.14.10, Unicode 16.0.0 (REVIEW-surface S1).

The reference interpreter of a run may be this PC's system 3.13.15 (Unicode 15.1.0); the product bundles 3.14.10
(build/make_release.py PYTHON_VERSION). Every table of the Rust crates that answers a question of Python's own text
(`str.isspace`, `int()`'s decimal digits, `unicodedata.bidirectional`, `str.isprintable`, `str.lower`/`casefold`, `\\w`,
`str.isalnum`) is made by the bundled interpreter (gen_tables.py, gen_codex.py, gen_policy.py: productpy.py), and these
diffs ask THAT interpreter, whatever runs the reference, so they hold on a 3.13 PC as on a 3.14 one:

* GeneratedTables - each generated table says it was made by 3.14.10 and `unicodedata` 16.0.0; the three generators'
  `--check` agree (each refuses a table made by another version: `productpy.stale`); car-store's own copy of the decimal
  zeros is car-machine's.
* ProductTables - every one of the 1,114,112 code points: `str.isspace`, `unicodedata.decimal`, the bidirectional class
  (L, R/AL), `str.isprintable`, `\\w`, `str.lower()` and `str.casefold()` - the product's Python's answer and Rust's, equal.
* Unicode16Cases - what the 3.13 tables got wrong, against the bundled interpreter running the tag's code: `int()` over
  the 80 digits of Unicode 16 (Garay, Myanmar Pao and Eastern Pwo Karen, Sunuwar, Gurung Khema, Kirat Rai, outlined,
  Ol Onal) read by the countdown and by `int(text, 16)`, the near-limit toast's own `int(percent)` texts of
  car-surface's ShippedInterpreterDiff (REVIEW-surface review8: `"\\U0001e5f9\\U0001e5f5"` is 84 used, "16% left"),
  and the bidirectional class of the letters Unicode 16 added, which `l10n.embedded` reads.
"""
from __future__ import annotations

import json
from pathlib import Path
import re
import subprocess
import sys
import unittest

import released
from rustdiff import core, diffs, productpy, reference
from rustdiff.leaves import Leaves, PRELUDE

ROOT = core.ROOT
HERE = Path(__file__).resolve().parent
RECORD: list[str] = []

# Every file a generator writes that holds Python's Unicode (car-store's seam/python.rs copy is checked beside them).
GENERATED = ("rust/crates/car-machine/src/pytext_tables.rs", "rust/crates/car-words/src/bidi_tables.rs",
             "rust/crates/car-codex/src/printable_gen.rs", "rust/crates/car-platform/src/printable_gen.rs",
             "rust/crates/car-policy/src/classify/text_tables.rs", "rust/crates/car-policy/src/settings/unicode_gen.rs",
             "advanced/rust/crates/car-adv/src/codex/alpha_gen.rs")
GENERATORS = ("gen_tables.py", "gen_codex.py", "gen_policy.py", "gen_advcodex.py")
# The zeros of the eight decimal runs Unicode 16.0 added over 15.1 (80 digits).
NEW_ZEROS = (0x10D40, 0x116D0, 0x116DA, 0x11BF0, 0x16130, 0x16D70, 0x1CCF0, 0x1E5F1)
# A letter of each script Unicode 16.0 added (bidirectional class: Garay R, the others L), and a Garay digit (AN).
NEW_LETTERS = (0x10D50, 0x16D40, 0x11BC0, 0x1E5D0, 0x16100, 0x11380, 0x11BE0, 0x16D6B, 0x10D40)


def zeros_of(path: str) -> list:
    text = (ROOT / path).read_text(encoding="utf-8")
    found = re.search(r"DECIMAL_ZEROS: &\[u32\] = &\[([^\]]*)\]", text)
    return [int(each, 16) for each in re.findall(r"0x[0-9A-Fa-f]+", found.group(1))]


class GeneratedTables(unittest.TestCase):
    def test_every_table_says_the_products_python(self):
        self.assertEqual((productpy.version(), productpy.unicode()), ("3.14.10", "16.0.0"))
        for relative in GENERATED:
            text = (ROOT / relative).read_text(encoding="utf-8")
            self.assertIsNone(productpy.stale(text, relative), relative)
            self.assertEqual(productpy.made_by(text), ("3.14.10", "16.0.0"), relative)
        RECORD.append("unicode16: %d generated tables say Python 3.14.10, unicodedata 16.0.0" % len(GENERATED))

    def test_a_table_of_another_version_is_refused(self):
        current = (ROOT / GENERATED[0]).read_text(encoding="utf-8")
        old = current.replace("Python 3.14.10 (unicodedata 16.0.0,", "Python 3.13.15 (unicodedata 15.1.0,")
        self.assertNotEqual(old, current)
        refused = productpy.stale(old, "pytext_tables.rs")
        self.assertIn("Python 3.13.15 (Unicode 15.1.0)", refused)
        self.assertIn("Python 3.14.10 (Unicode 16.0.0)", refused)
        first = "// Generated by tests/rustdiff/gen_tables.py from Python 3.13.15's `str` and `unicodedata` 15.1.0. Do not edit.\n"
        self.assertEqual(productpy.made_by(first), ("3.13.15", "15.1.0"))  # the first generators' header, refused too
        self.assertIsNotNone(productpy.stale(first, "x"))
        self.assertIsNotNone(productpy.stale("// no stamp at all\n", "x"))
        # the right Unicode on the wrong Python is refused as well, and so is the right Python with the old Unicode
        self.assertIsNotNone(productpy.stale(current.replace("Python 3.14.10", "Python 3.14.7"), "x"))
        self.assertIsNotNone(productpy.stale(current.replace("unicodedata 16.0.0", "unicodedata 15.1.0"), "x"))

    def test_the_generators_check_agrees_under_any_starting_python(self):
        for name in GENERATORS:
            done = subprocess.run(reference.script_command(HERE / name, "--check", paths=[]), cwd=str(ROOT),
                                  capture_output=True, creationflags=reference.NO_WINDOW, timeout=900)
            self.assertEqual(done.returncode, 0, "%s --check: %s%s" % (name, done.stdout.decode("utf-8", "replace"),
                                                                      done.stderr.decode("utf-8", "replace")))
        RECORD.append("unicode16: gen_tables, gen_codex, gen_policy and gen_advcodex --check agree, started by the reference's "
                      "Python %s and run under the bundled runtime" % reference.refpython.version())

    def test_car_stores_copy_of_the_decimal_zeros_is_car_machines(self):
        mine = zeros_of("rust/crates/car-store/src/seam/python.rs")
        theirs = zeros_of("rust/crates/car-machine/src/pytext_tables.rs")
        self.assertEqual(mine, theirs)
        self.assertEqual(len(theirs), 76)
        self.assertTrue(set(NEW_ZEROS) <= set(theirs))


# What the bundled interpreter says of every code point, in one process: the diff of the tables themselves.
TABLES = r'''
import json, re, sys, unicodedata
word = re.compile(r"\w")
classes, bidi, printable, words, lowered, folded = [], [], [], [], [], []
for point in range(0x110000):
    if 0xD800 <= point < 0xE000:
        classes.append("-"); bidi.append("-"); printable.append("0"); words.append("-")
        continue
    char = chr(point)
    value = unicodedata.decimal(char, None)
    classes.append("S" if char.isspace() else ("-" if value is None else str(value)))
    kind = unicodedata.bidirectional(char)
    bidi.append("L" if kind == "L" else "R" if kind in ("R", "AL") else "-")
    printable.append("1" if char.isprintable() else "0")
    words.append("w" if word.match(char) else ".")
    if char.lower() != char:
        lowered.append([point, char.lower()])
    if char.casefold() != char:
        folded.append([point, char.casefold()])
sys.stdout.write(json.dumps({"python": list(sys.version_info[:3]), "unicode": unicodedata.unidata_version,
                             "classes": "".join(classes), "bidi": "".join(bidi), "printable": "".join(printable),
                             "words": "".join(words), "lowered": lowered, "folded": folded}, ensure_ascii=False))
'''


def on_product(script: str, *, profile: Path, tag: str | None = None) -> subprocess.CompletedProcess:
    """`script` under the bundled interpreter, the tag's package on its path, every home the scratch one."""
    environment = reference.scratch_environment(profile, PYTHONPATH=str(released.package(tag or reference.TAG)))
    return productpy.run(["-c", script], env=environment, cwd=str(profile), capture=True)


class ProductTables(Leaves):
    def test_every_code_point(self):
        made = on_product(TABLES, profile=self.profile("product-tables"))
        self.assertEqual(made.returncode, 0, made.stderr[-2000:].decode("utf-8", "replace"))
        theirs = json.loads(made.stdout.decode("utf-8"))
        self.assertEqual((theirs["python"], theirs["unicode"]), ([3, 14, 10], "16.0.0"))
        rust = self.rust("leaves.batch", cases=[["pytext.classes"], ["bidi.classes"], ["classify.tables"]] + [
            ["codex.printable", start, min(start + 0x10000, 0x110000)] for start in range(0, 0x110000, 0x10000)])["value"]
        got_classes, got_bidi, got_tables = rust[0]["ok"], rust[1]["ok"], rust[2]["ok"]
        got_printable = "".join(each["ok"] for each in rust[3:])
        for name, want, have in (("isspace/decimal", theirs["classes"], got_classes), ("bidi L/R", theirs["bidi"], got_bidi),
                                 ("isprintable", theirs["printable"], got_printable), ("\\w", theirs["words"], got_tables[0])):
            self.assertEqual(len(want), len(have), name)
            if want != have:
                point = next(index for index, (a, b) in enumerate(zip(want, have)) if a != b)
                self.fail("%s differs at U+%04X: Python 3.14.10 says %r, Rust says %r (gen_*.py --write)" % (
                    name, point, want[point], have[point]))
        self.assertEqual(got_tables[1], theirs["lowered"], "str.lower() differs")
        self.assertEqual(got_tables[2], theirs["folded"], "str.casefold() differs")
        RECORD.append("unicode16: isspace, decimal, bidi L/R, isprintable, \\w, lower() and casefold() of all 1,114,112 code points "
                      "equal Python 3.14.10's (Unicode %s), whatever runs the reference" % theirs["unicode"])


CASES = r'''
import unicodedata
from codex_auto_resume import l10n
from codex_auto_resume.ui import words
ZEROS = %(zeros)r
LETTERS = %(letters)r
digit_texts = []
for zero in ZEROS:
    ten = "".join(chr(zero + step) for step in range(10))
    digit_texts += [chr(zero + step) for step in range(10)]
    digit_texts += [ten, chr(zero + 9) + chr(zero + 5), " " + chr(zero + 4) + chr(zero + 2) + " ", "+" + chr(zero + 7),
                    chr(zero + 1) + "_" + chr(zero) + chr(zero), chr(zero + 3) + "5", "7" + chr(zero + 3), chr(zero + 5) + ".5",
                    chr(zero + 8) + "\n", "-" + chr(zero + 2)]
# the near-limit toast's, sleep notice's and memory notice's texts (review8 ShippedInterpreterDiff) and neighbours
texts = ["\u0669\u0665", " 95 ", "9_5", "+95", "95\n", "\u0665", "\uff19\uff15", "0x5f", "95.0", "1" * 300, "-0", "\u00b2", "\u2167",
         "\U0001e5f9\U0001e5f5", "\U00010d49\U00010d45", "\U00010d40\U00010d41", "\U0001ccf9\U0001ccf5", "\U00016d79\U00016d75",
         "\U00011bf9\U00011bf5", "\U00016139\U00016135", "\U000116d9\U000116d5", "\U000116e3\U000116df"]
cases = []
for text in digit_texts + texts:
    cases.append(["words.countdown", text])
    cases.append(["pytext.int16", text])
    cases.append(["near.left", text])
# int() of a single character: the digits and the neighbours of each run
for point in sorted({zero + shift for zero in ZEROS for shift in range(-3, 14)}):
    cases.append(["words.countdown", chr(point)])
strings = []
for letter in LETTERS:
    char = chr(letter)
    strings += [char, "1" + char, "(" + char + ")", "ab" + char + "\u05d0", char + "9", "C:\\x" + char]
for value in strings:
    cases.append(["l10n.first_strong", value])
    for locale in l10n.LOCALES:
        cases.append(["l10n.embedded", value, locale])

def near_left(text):
    # car-surface's near_limit_content: the share left, 100 - clamp(int(percent)); a text int() cannot read says none
    try:
        return 100 - max(0, min(100, int(text)))
    except (TypeError, ValueError, OverflowError):
        return None

ops = {"words.countdown": words.countdown, "pytext.int16": lambda s: (lambda n: [n < 0, str(abs(n)) if abs(n) < 2 ** 128 else None])(int(s, 16)),
       "l10n.first_strong": l10n.first_strong, "l10n.embedded": l10n.embedded, "near.left": near_left}
finish(cases, ops)
''' % {"zeros": NEW_ZEROS, "letters": NEW_LETTERS}


class Unicode16Cases(Leaves):
    def test_digits_and_letters_unicode_16_added(self):
        made = on_product(PRELUDE + CASES, profile=self.profile("product-cases"))
        self.assertEqual(made.returncode, 0, made.stderr[-3000:].decode("utf-8", "replace"))
        done = json.loads(made.stdout.decode("utf-8"))
        cases, expected = done["cases"], done["results"]
        # The car-surface half: car-surface is not in this tree, so Rust has no op for `near_limit_content`; its share is
        # `100 - clamp(int(text))` and its `int` is car-machine's pytext, which the countdown reads the same way. The
        # near.left cases are the Python half of review8's ShippedInterpreterDiff texts, asserted below.
        by_text = {case[1]: result for case, result in zip(cases, expected) if case[0] == "words.countdown"}
        left = {case[1]: result for case, result in zip(cases, expected) if case[0] == "near.left"}
        self.assertEqual(by_text["\U0001e5f9\U0001e5f5"], {"ok": "1:24"}, "the product's int() reads Ol Onal 84")
        self.assertEqual(left["\U0001e5f9\U0001e5f5"], {"ok": 16}, "so the near-limit toast says 16% left")
        self.assertEqual(by_text["\U00010d40\U00010d41"], {"ok": "1s"})  # Garay 0, 1: "01"
        self.assertEqual(left["\U00010d49\U00010d45"], {"ok": 5})  # Garay 9, 5: 95 used
        rust_cases = [case for case in cases if case[0] != "near.left"]
        rust_expected = [result for case, result in zip(cases, expected) if case[0] != "near.left"]
        actual = []
        with core.Harness(reference.scratch_environment(self.profile("rust-unicode16"))) as harness:
            for start in range(0, len(rust_cases), 2000):
                number, line = harness.call("leaves.batch", cases=rust_cases[start:start + 2000])
                reply = json.loads(line.decode("utf-8"))
                self.assertEqual(reply.get("id"), number, line[:300])
                self.assertTrue(reply["reply"].get("ok"), line[:600])
                actual += reply["reply"]["value"]
        self.assertEqual(len(actual), len(rust_expected))
        bad = ["case %s\n    Python 3.14.10 %s\n    rust          %s" % (
            json.dumps(case, ensure_ascii=True)[:200], json.dumps(want, ensure_ascii=True)[:200], json.dumps(got, ensure_ascii=True)[:200])
            for case, want, got in zip(rust_cases, rust_expected, actual) if diffs.encode(want) != diffs.encode(got)]
        self.assertEqual(bad, [], "%d of %d cases differ\n  %s" % (len(bad), len(rust_cases), "\n  ".join(bad[:12])))
        accepted = sum(1 for case, result in zip(rust_cases, rust_expected) if case[0] == "words.countdown" and "ok" in result)
        self.assertGreater(accepted, 80 * 2)
        RECORD.append("unicode16: %d cases (int() over the 80 new digits and the review8 texts by countdown and int(,16); the "
                      "bidi class of %d new letters through first_strong and embedded) equal Python 3.14.10 running the "
                      "tag's code (%d countdowns read a number)" % (len(rust_cases), len(NEW_LETTERS), accepted))
