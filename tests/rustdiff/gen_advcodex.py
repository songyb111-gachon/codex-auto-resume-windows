"""Generate S7.2c's one Unicode table, from the reference Python's own `str`.

    python -X utf8 tests/rustdiff/gen_advcodex.py --write | --check

`str.isalpha()` (codex/turns.py's item kinds, codex/sessions.py's words) is true of the letters of Python's Unicode
database (Lm, Lt, Lu, Ll, Lo), which is not Rust's `char::is_alphabetic` (that takes Nl and Other_Alphabetic too).
The table is the code points it is true of, as inclusive ranges, written to car-adv/src/codex/alpha_gen.rs. The
Python that makes it is the one the product ships (build/make_release.py PYTHON_VERSION, 3.14.10: Unicode 16.0.0): the script
runs itself under the bundled runtime (productpy.py), the file says which Python and `unicodedata` made it, and --check
refuses a file made by any other. diffs_advcodex_readers asks both sides.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))  # the embeddable runtime has no script directory on its path
import productpy  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "advanced" / "rust" / "crates" / "car-adv" / "src" / "codex" / "alpha_gen.rs"


def ranges(points):
    found, start, last = [], None, None
    for point in points:
        if start is None:
            start = last = point
        elif point == last + 1:
            last = point
        else:
            found.append((start, last))
            start = last = point
    if start is not None:
        found.append((start, last))
    return found


def text() -> str:
    pairs = ranges(point for point in range(0x110000) if chr(point).isalpha())
    lines = ["// Generated by tests/rustdiff/gen_advcodex.py from `str.isalpha` of %s. Do not edit." % productpy.stamp(),
             "/// The code points `str.isalpha()` is true of, as inclusive ranges.",
             "pub static ALPHA: &[(u32, u32)] = &["]
    lines += ["    (0x%X, 0x%X)," % pair for pair in pairs]
    lines += ["];", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    ran = productpy.ensure(__file__, sys.argv[1:] if argv is None else argv)
    if ran is not None:
        return ran
    made = text()
    if args.write:
        TARGET.write_bytes(made.encode("utf-8"))
        return 0
    current = TARGET.read_bytes().decode("utf-8").replace("\r\n", "\n") if TARGET.is_file() else ""
    refused = productpy.stale(current, TARGET.relative_to(ROOT).as_posix())
    if refused or current != made:
        print(refused or "%s is stale: run gen_advcodex.py --write" % TARGET.relative_to(ROOT))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
