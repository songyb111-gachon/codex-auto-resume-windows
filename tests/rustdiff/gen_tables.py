"""Generate the Unicode tables the ports read, from the reference Python's own `unicodedata` and `str`.

    python -X utf8 tests/rustdiff/gen_tables.py --write | --check

Python text answers by its own Unicode database, which Rust's `char` does not match exactly (`str.isspace`
is true of U+001C..U+001F, `d` and `int()` take every decimal digit of every script, `unicodedata.bidirectional`
is Unicode 15.1 or 16 by the interpreter). The ports (car-machine's `pytext`, car-words' bidi) therefore
read tables made here, and the diffs (diffs_leaves_machine, diffs_leaves_words) ask both sides about every
one of the 1,114,112 code points, so a table that goes stale fails a test.

The Python that makes them is the one the product ships (build/make_release.py PYTHON_VERSION, 3.14.10: Unicode 16.0.0;
this PC's system 3.13 is Unicode 15.1.0 and misses 80 digits `int()` reads in the product): the script runs itself under
the bundled runtime (productpy.py), each file says which Python and `unicodedata` made it, and --check refuses a file made
by any other.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys
import unicodedata

sys.path.insert(0, str(Path(__file__).resolve().parent))  # the embeddable runtime has no script directory on its path
import productpy  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SURROGATES = range(0xD800, 0xE000)


def ranges(points):
    found, start, last = [], None, None
    for point in points:
        if start is None:
            start = last = point
        elif point == last + 1:
            last = point
        else:
            found.append((start, last))
            start = last = point
    if start is not None:
        found.append((start, last))
    return found


def render(pairs) -> str:
    return "&[" + ", ".join("(0x%X, 0x%X)" % pair for pair in pairs) + "]"


def machine() -> str:
    spaces = ranges(point for point in range(0x110000) if chr(point).isspace())
    zeros = []
    for point in range(0x110000):
        if point in SURROGATES:
            continue
        value = unicodedata.decimal(chr(point), None)
        if value == 0:
            for step in range(10):
                assert unicodedata.decimal(chr(point + step), None) == step, hex(point)
            zeros.append(point)
    decimals = sum(1 for point in range(0x110000) if point not in SURROGATES
                   and unicodedata.decimal(chr(point), None) is not None)
    assert decimals == 10 * len(zeros), "a decimal digit outside a run of ten"
    return "\n".join([
        "// Generated by tests/rustdiff/gen_tables.py from `str` and `unicodedata` of %s. Do not edit." % productpy.stamp(),
        "/// The code points `str.isspace()` is true of, as inclusive ranges.",
        "pub static SPACE: &[(u32, u32)] = %s;" % render(spaces)[0:],
        "/// The code points of value 0 of the decimal digits (`unicodedata.decimal`): each starts a run of ten.",
        "pub static DECIMAL_ZEROS: &[u32] = &[%s];" % ", ".join("0x%X" % zero for zero in zeros),
        ""])


def words() -> str:
    classes = {"L": [], "R": [], "AL": []}
    for point in range(0x110000):
        if point in SURROGATES:
            continue
        kind = unicodedata.bidirectional(chr(point))
        if kind in classes:
            classes[kind].append(point)
    return "\n".join([
        "// Generated by tests/rustdiff/gen_tables.py from `unicodedata` of %s. Do not edit." % productpy.stamp(),
        "/// The code points whose bidirectional class is L, R and AL (`unicodedata.bidirectional`), as inclusive ranges;",
        "/// a surrogate is none of them, and so is every other class.",
        "pub static LEFT_TO_RIGHT: &[(u32, u32)] = %s;" % render(ranges(classes["L"])),
        "pub static RIGHT_TO_LEFT: &[(u32, u32)] = %s;" % render(ranges(classes["R"])),
        "pub static ARABIC_LETTER: &[(u32, u32)] = %s;" % render(ranges(classes["AL"])),
        ""])


FILES = {"rust/crates/car-machine/src/pytext_tables.rs": machine,
         "rust/crates/car-words/src/bidi_tables.rs": words}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    ran = productpy.ensure(__file__, sys.argv[1:] if argv is None else argv)
    if ran is not None:
        return ran
    status = 0
    for relative, make in FILES.items():
        text, path = make(), ROOT / relative
        if args.write:
            path.write_bytes(text.encode("utf-8"))
            continue
        current = path.read_bytes().decode("utf-8") if path.is_file() else ""
        refused = productpy.stale(current, relative)
        if refused or current != text:
            print(refused or "%s is not what Python %s makes: run gen_tables.py --write" % (relative, sys.version.split()[0]))
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
