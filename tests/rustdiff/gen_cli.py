"""Write car-bin's command-line tables (`rust/crates/car-bin/src/parsers_gen.rs`) from the reference tag's own parsers.

The four argparse parsers `codex-auto-resume.exe` stands in for - `cli.build_parser()` (prog auto_resume),
`scripts/plugin_setup.py`'s `build_parser()` (prog plugin_setup), `controlcli.build_parser()` (prog
codex-auto-resume-control, the `bridge` role) and `mcpserver.main`'s (prog codex-auto-resume-mcp, the `mcp` role) - are
read from the tag (`released.package`), every action with its option strings, dest, nargs, default, type, choices and
metavar, and every parser's usage and help text as argparse formats them in a pipe (no COLUMNS: 80 wide), so car-bin's
parser (`argparse.rs`) accepts, refuses and prints exactly what the tag's does.

    python -X utf8 tests/rustdiff/gen_cli.py --write [--reference v0.6.26]
    python -X utf8 tests/rustdiff/gen_cli.py --check     # exit 1 when the committed file is stale
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TARGET = ROOT / "rust" / "crates" / "car-bin" / "src" / "parsers_gen.rs"
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)

DUMP = r'''
import argparse, importlib.util, json, os, sys
os.environ.pop("COLUMNS", None)
os.environ.pop("LINES", None)
source = sys.argv[1]
sys.path.insert(0, os.path.join(source, "src"))
from codex_auto_resume import cli, controlcli
spec = importlib.util.spec_from_file_location("plugin_setup", os.path.join(source, "scripts", "plugin_setup.py"))
plugin_setup = importlib.util.module_from_spec(spec)
spec.loader.exec_module(plugin_setup)
mcp = argparse.ArgumentParser(prog="codex-auto-resume-mcp", add_help=True)
mcp.add_argument("--home", help="runtime home (default: the installed location)")

def kind(action):
    if isinstance(action, argparse._HelpAction):
        return "help"
    if isinstance(action, argparse._StoreTrueAction):
        return "flag"
    if isinstance(action, argparse._SubParsersAction):
        return "commands"
    if type(action) is argparse._StoreAction:
        return "store"
    raise SystemExit("an action car-bin does not take: %r" % (action,))

def typed(action):
    return {None: "str", int: "int", float: "float"}[action.type]

parsers = []
def add(parser):
    index = len(parsers)
    entry = {"prog": parser.prog, "usage": parser.format_usage(), "help": parser.format_help(), "actions": []}
    parsers.append(entry)
    for action in parser._actions:
        made = {"kind": kind(action), "strings": list(action.option_strings), "dest": action.dest,
                "nargs": action.nargs, "required": bool(action.required),
                "metavar": action.metavar, "default": action.default if action.default is not argparse.SUPPRESS
                else None}
        if made["kind"] == "commands":
            made["commands"] = [[name, add(sub)] for name, sub in action.choices.items()]
        else:
            made["type"] = typed(action) if made["kind"] == "store" else "str"
            made["choices"] = None if action.choices is None else [str(each) for each in action.choices]
        entry["actions"].append(made)
    return index

roots = {name: add(parser) for name, parser in (("cli", cli.build_parser()), ("setup", plugin_setup.build_parser()),
                                                ("bridge", controlcli.build_parser()), ("mcp", mcp))}
print(json.dumps({"roots": roots, "parsers": parsers, "python": sys.version.split()[0]}))
'''


def rust_text(text) -> str:
    if text is None:
        return "None"
    return "Some(%s)" % json.dumps(text)


def rust_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render(dump: dict, tag: str) -> str:
    lines = ["// @generated by tests/rustdiff/gen_cli.py from %s's parsers (Python %s): do not edit." % (
        tag, dump["python"]),
        "#![allow(clippy::all)]", "use crate::argparse::{Action, Kind, Nargs, Parser, Ty};", ""]
    for name, index in sorted(dump["roots"].items()):
        lines.append("pub const %s: usize = %d;" % (name.upper(), index))
    lines.append("")
    lines.append("pub static PARSERS: &[Parser] = &[")
    for parser in dump["parsers"]:
        lines.append("    Parser {")
        lines.append("        prog: %s," % rust_str(parser["prog"]))
        lines.append("        usage: %s," % rust_str(parser["usage"]))
        lines.append("        help: %s," % rust_str(parser["help"]))
        lines.append("        actions: &[")
        for action in parser["actions"]:
            nargs = {None: "Nargs::One", "?": "Nargs::Optional", 0: "Nargs::Zero", "A...": "Nargs::Parser"}[
                action["nargs"]]
            kind = {"help": "Kind::Help", "flag": "Kind::Flag", "store": "Kind::Store",
                    "commands": "Kind::Commands"}[action["kind"]]
            default = action["default"]
            if isinstance(default, bool) or default is None:
                default_text = "None"
            else:
                default_text = "Some(%s)" % rust_str(str(default))
            commands = ", ".join("(%s, %d)" % (rust_str(name), index) for name, index in action.get("commands", []))
            choices = action.get("choices")
            choices_text = "None" if choices is None else "Some(&[%s])" % ", ".join(rust_str(each) for each in choices)
            lines.append("            Action { kind: %s, strings: &[%s], dest: %s, nargs: %s, required: %s, "
                         "metavar: %s, default: %s, ty: Ty::%s, choices: %s, commands: &[%s] }," % (
                             kind, ", ".join(rust_str(each) for each in action["strings"]), rust_str(action["dest"]),
                             nargs, "true" if action["required"] else "false",
                             "None" if action["metavar"] is None else "Some(%s)" % rust_str(action["metavar"]),
                             default_text, {"str": "Str", "int": "Int", "float": "Float"}[action.get("type", "str")],
                             choices_text, commands))
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    return "\n".join(lines) + "\n"


_TREES: dict = {}


def tree(tag: str) -> Path:
    """`tag`'s src, scripts and plugin manifest taken out of git once, into a temporary folder (released.package takes
    src alone; plugin_setup.py is in scripts)."""
    import atexit
    import io
    import shutil
    import tarfile
    import tempfile

    if tag in _TREES:
        return _TREES[tag]
    archive = subprocess.run(["git", "-C", str(ROOT), "archive", "--format=tar", tag, "src", "scripts",
                              ".codex-plugin/plugin.json", "assets"], capture_output=True, creationflags=NO_WINDOW)
    if archive.returncode != 0:
        raise SystemExit("%s is not in this checkout" % tag)
    folder = Path(tempfile.mkdtemp(prefix="car-v0627-mcp-tree-%s-" % tag))
    atexit.register(shutil.rmtree, folder, True)
    with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tar:
        tar.extractall(folder, filter="data")
    _TREES[tag] = folder
    return folder


def made(tag: str) -> str:
    tree_ = tree(tag)
    sys.path[:0] = [str(ROOT / "src"), str(ROOT / "tests")]
    from rustdiff import reference  # the reference's Python (`--reference-python`), not sys.executable
    done = subprocess.run(reference.command(DUMP, tree_, paths=[tree_ / "src"]), capture_output=True,
                          creationflags=NO_WINDOW, timeout=300, env={k: v for k, v in os.environ.items()
                                                                     if k not in ("COLUMNS", "LINES", "PYTHONPATH")})
    if done.returncode != 0:
        raise SystemExit(done.stderr.decode("utf-8", "replace"))
    return render(json.loads(done.stdout.decode("utf-8")), tag)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="tests/rustdiff/gen_cli.py")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reference", default="v0.6.26")
    args = parser.parse_args(argv)
    text = made(args.reference)
    if args.write:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
        print("wrote %s" % TARGET.relative_to(ROOT).as_posix())
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
    if current != text:
        print("stale: %s (run with --write)" % TARGET.relative_to(ROOT).as_posix())
        return 1
    print("fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
