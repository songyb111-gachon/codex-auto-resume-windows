"""The host's table of strong directions (gui/SurfaceBidi.cs), written from Python's own unicodedata.

l10n.first_strong reads unicodedata.bidirectional; .NET Framework has no bidirectional class, so the host carries the
runs of the classes first_strong tells apart - L, and R or AL - as Python's Unicode database has them. Run from the
worktree root to write the file again: `python -X utf8 tests/surfacebidi.py`. tests/test_surface_parity.py holds the
file equal to what this writes (under the Unicode version the file names).
"""
from __future__ import annotations

from pathlib import Path
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "gui" / "SurfaceBidi.cs"


def runs() -> list:
    """(first code point, "L" | "R" | "") for each run of one class, from 0 to the last code point."""
    found, previous = [], None
    for point in range(0x110000):
        kind = unicodedata.bidirectional(chr(point))
        kind = "L" if kind == "L" else ("R" if kind in ("R", "AL") else "")
        if kind != previous:
            found.append((point, kind))
            previous = kind
    return found


def source() -> str:
    table = runs()
    entries = ["0x%X" % point for point, _ in table]
    kinds = "".join(kind or "-" for _, kind in table)
    body = ",\n".join("            " + ",".join(entries[at:at + 16]) for at in range(0, len(entries), 16))
    return ("""// Codex Auto Resume - which way a piece of text reads, by its first strong character (v0.6.27, S6.3).
//
// GENERATED by tests/surfacebidi.py from Python's unicodedata (Unicode %s): do not edit. l10n.first_strong's
// table: the runs of code points whose bidirectional class is L, or R or AL, every other one "-".
using System.Collections.Generic;

namespace CodexAutoResume
{
    internal static class SurfaceBidi
    {
        internal const string UnicodeVersion = "%s";

        private static readonly int[] Starts = {
%s
        };

        private const string Kinds = "%s";

        private static char KindOf(int point)
        {
            int low = 0, high = Starts.Length - 1;
            while (low < high)
            {
                int middle = (low + high + 1) / 2;
                if (Starts[middle] <= point) low = middle; else high = middle - 1;
            }
            return Kinds[low];
        }

        /// "L" or "R" by the first character of `value` with a direction of its own, null when it has none
        /// (l10n.first_strong): code point by code point, a lone surrogate as itself, as Python reads a str.
        internal static string FirstStrong(string value)
        {
            if (value == null) return null;
            for (int at = 0; at < value.Length; at++)
            {
                int point = value[at];
                if (char.IsHighSurrogate(value[at]) && at + 1 < value.Length && char.IsLowSurrogate(value[at + 1]))
                {
                    point = char.ConvertToUtf32(value[at], value[at + 1]);
                    at++;
                }
                char kind = KindOf(point);
                if (kind == 'L') return "L";
                if (kind == 'R') return "R";
            }
            return null;
        }
    }
}
""" % (unicodedata.unidata_version, unicodedata.unidata_version, body, kinds))


if __name__ == "__main__":
    TARGET.write_text(source(), encoding="utf-8", newline="\n")
    sys.stdout.write("wrote %s (Unicode %s)\n" % (TARGET.relative_to(ROOT).as_posix(), unicodedata.unidata_version))
