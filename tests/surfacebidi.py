"""The host's table of strong directions (gui/SurfaceBidi.cs), written from the product's Python's own unicodedata.

l10n.first_strong reads unicodedata.bidirectional; .NET Framework has no bidirectional class, so the host carries the
runs of the classes first_strong tells apart - L, and R or AL - as the product's Python has them. That Python is the
bundled CPython 3.14.10 (build/make_release.py PYTHON_VERSION), whose Unicode is 16.0.0 (DECISIONS.md: the product
follows its bundled runtime), not whatever Python starts this script: so the script runs itself again under the bundled
embeddable runtime (tests/rustdiff/refpython.py, always `bundled`, whatever --reference-python says - a table of
Python's Unicode is the product's Python's) and refuses any Unicode but UNICODE.

    python -X utf8 tests/surfacebidi.py [--write]   write the file again
    python -X utf8 tests/surfacebidi.py --check     exit 0 when the file is what the bundled Python writes, 1 when not
                                                    (or when it names another Unicode), 2 when the runtime is not 16.0.0

tests/test_surface_parity.py runs --check, and asks the same runtime for the reference's first_strong (`first_strong`).
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import subprocess
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "gui" / "SurfaceBidi.cs"
# The Unicode of the product's bundled Python (3.14.10): the only one this table may be written from.
UNICODE = "16.0.0"
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)
CHILD = "import sys, surfacebidi; sys.exit(surfacebidi.child(sys.argv[1:]))"


def runs() -> list:
    """(first code point, "L" | "R" | "") for each run of one class, from 0 to the last code point."""
    found, previous = [], None
    for point in range(0x110000):
        kind = unicodedata.bidirectional(chr(point))
        kind = "L" if kind == "L" else ("R" if kind in ("R", "AL") else "")
        if kind != previous:
            found.append((point, kind))
            previous = kind
    return found


# The characters a run's first code point is written with (see pack): the base 64 alphabet, no quote and no backslash.
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
LINE = 100


def pack(starts) -> str:
    """The runs' first code points as the distance from the one before (the first from 0), 5 bits to a character, the
    sixth bit set while more follow, least significant bits first."""
    out, previous = [], 0
    for start in starts:
        distance, previous = start - previous, start
        while True:
            chunk, distance = distance & 31, distance >> 5
            out.append(ALPHABET[chunk | 32 if distance else chunk])
            if not distance:
                break
    return "".join(out)


def unpack(packed: str) -> list:
    """pack's inverse, as gui/SurfaceBidi.cs's Unpack reads it."""
    starts, at, previous = [], 0, 0
    while at < len(packed):
        distance, shift = 0, 0
        while True:
            digit = ALPHABET.index(packed[at])
            at += 1
            distance |= (digit & 31) << shift
            shift += 5
            if not digit & 32:
                break
        previous += distance
        starts.append(previous)
    return starts


def source() -> str:
    table = runs()
    starts = [point for point, _ in table]
    kinds = "".join(kind or "-" for _, kind in table)
    packed = pack(starts)
    assert unpack(packed) == starts
    body = " +\n".join('            "%s"' % packed[at:at + LINE] for at in range(0, len(packed), LINE))
    return ("""// Codex Auto Resume - which way a piece of text reads, by its first strong character (v0.6.27, S6.3).
//
// GENERATED by tests/surfacebidi.py from the bundled Python's unicodedata (Unicode %s): do not edit. l10n.first_strong's
// table: the runs of code points whose bidirectional class is L, or R or AL, every other one "-".
using System.Collections.Generic;

namespace CodexAutoResume
{
    internal static class SurfaceBidi
    {
        internal const string UnicodeVersion = "%s";

        // The first code point of each run, as the distance from the one before it (the first from 0): 5 bits to a
        // character, the sixth bit set while more follow, least significant first, the characters of the base 64 alphabet.
        // A constant int[] this size is a <PrivateImplementationDetails>{GUID} class, which the in-box compiler names at
        // random and build/normalize_pe.py refuses, so the table is built once, when the class is first used.
        private const string Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        private const string Packed =
%s;

        private const string Kinds = "%s";

        private static readonly int[] Starts = Unpack(Packed);

        private static int[] Unpack(string packed)
        {
            var starts = new List<int>(Kinds.Length);
            int at = 0, previous = 0;
            while (at < packed.Length)
            {
                int distance = 0, shift = 0, digit;
                do
                {
                    digit = Alphabet.IndexOf(packed[at++]);
                    distance |= (digit & 31) << shift;
                    shift += 5;
                } while ((digit & 32) != 0);
                previous += distance;
                starts.Add(previous);
            }
            return starts.ToArray();
        }

        private static char KindOf(int point)
        {
            int low = 0, high = Starts.Length - 1;
            while (low < high)
            {
                int middle = (low + high + 1) / 2;
                if (Starts[middle] <= point) low = middle; else high = middle - 1;
            }
            return Kinds[low];
        }

        /// "L" or "R" by the first character of `value` with a direction of its own, null when it has none
        /// (l10n.first_strong): code point by code point, a lone surrogate as itself, as Python reads a str.
        internal static string FirstStrong(string value)
        {
            if (value == null) return null;
            for (int at = 0; at < value.Length; at++)
            {
                int point = value[at];
                if (char.IsHighSurrogate(value[at]) && at + 1 < value.Length && char.IsLowSurrogate(value[at + 1]))
                {
                    point = char.ConvertToUtf32(value[at], value[at + 1]);
                    at++;
                }
                char kind = KindOf(point);
                if (kind == 'L') return "L";
                if (kind == 'R') return "R";
            }
            return null;
        }
    }
}
""" % (unicodedata.unidata_version, unicodedata.unidata_version, body, kinds))


def stamp(text: str):
    """The Unicode version a written table names (its `UnicodeVersion`), or None."""
    found = re.search(r'UnicodeVersion = "([^"]+)"', text)
    return found.group(1) if found else None


def child(arguments) -> int:
    """The half that runs under the bundled runtime: refuses another Unicode, then writes, checks or answers."""
    if unicodedata.unidata_version != UNICODE:
        sys.stderr.write("refused: this Python (%s) has Unicode %s; the table is the bundled Python's Unicode %s\n"
                         % (sys.version.split()[0], unicodedata.unidata_version, UNICODE))
        return 2
    if "--first-strong" in arguments:
        from codex_auto_resume import l10n
        texts = json.loads(sys.stdin.buffer.read().decode("utf-8"))
        sys.stdout.buffer.write(json.dumps([l10n.first_strong(text) for text in texts]).encode("utf-8"))
        return 0
    made = source()
    if "--check" in arguments:
        written = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if stamp(written) != UNICODE:
            sys.stderr.write("%s names Unicode %s, not %s: run `python -X utf8 tests/surfacebidi.py`\n"
                             % (TARGET.relative_to(ROOT).as_posix(), stamp(written), UNICODE))
            return 1
        if written != made:
            sys.stderr.write("%s is stale: run `python -X utf8 tests/surfacebidi.py`\n" % TARGET.relative_to(ROOT).as_posix())
            return 1
        return 0
    TARGET.write_text(made, encoding="utf-8", newline="\n")
    sys.stdout.write("wrote %s (Unicode %s, Python %s)\n"
                     % (TARGET.relative_to(ROOT).as_posix(), unicodedata.unidata_version, sys.version.split()[0]))
    return 0


def run(arguments, given: bytes | None = None) -> subprocess.CompletedProcess:
    """`child(arguments)` under the bundled runtime (refpython.py's embeddable 3.14.10, unpacked in a scratch folder)."""
    sys.path.insert(0, str(ROOT / "tests" / "rustdiff"))
    try:
        import refpython
    finally:
        sys.path.pop(0)
    paths = [ROOT / "tests", ROOT / "src"]
    environment = dict(os.environ, PYTHONPATH=os.pathsep.join(str(each) for each in paths))
    return subprocess.run(refpython.command(CHILD, *arguments, paths=paths, which="bundled"), input=given,
                          capture_output=True, env=environment, creationflags=NO_WINDOW, timeout=600)


def first_strong(texts) -> list:
    """l10n.first_strong of each text as the product's Python answers it (the bundled runtime's Unicode)."""
    done = run(["--first-strong"], json.dumps(list(texts)).encode("utf-8"))
    if done.returncode != 0:
        raise RuntimeError("the bundled Python's first_strong failed:\n%s" % done.stderr.decode("utf-8", "replace"))
    return json.loads(done.stdout.decode("utf-8"))


def main(arguments) -> int:
    done = run(arguments)
    sys.stdout.write(done.stdout.decode("utf-8", "replace"))
    sys.stderr.write(done.stderr.decode("utf-8", "replace"))
    return done.returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
